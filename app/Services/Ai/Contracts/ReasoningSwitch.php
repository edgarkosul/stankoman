<?php

namespace App\Services\Ai\Contracts;

/**
 * Клиент модели, который умеет ответить без рассуждений.
 *
 * Нужен одному месту — повтору пустого ответа (ShopAssistant). У
 * deepseek-v4-flash и v4.1 пустой ответ — это рассуждения, съевшие потолок
 * токенов: 1 100–1 500 токенов вывода и 50–70 с ожидания (замеры bots
 * 28–29.09.2026). Тот же вызов ещё раз может снова уйти в рассуждения;
 * без них ответ приходит за секунды.
 *
 * Выключать рассуждения насовсем нельзя: ответы от этого быстрее не стали
 * (прод bots, 30.09), а модель реже ходит в каталог за характеристиками.
 */
interface ReasoningSwitch
{
    public function withoutReasoning(): LlmClient;
}
