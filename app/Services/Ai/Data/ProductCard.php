<?php

namespace App\Services\Ai\Data;

/**
 * Товар в том виде, в каком его можно показать модели.
 *
 * Ценовая политика магазина уже применена, и это не удобство, а защита.
 * Магазин прячет от гостя СУММУ скидки для зарегистрированных, но показывает
 * её ПРОЦЕНТ (DiscountVisibility, решение заказчика от 20.08.2026), и на деве
 * скидка стоит у 1 897 товаров из 4 001 — это основной режим, а не краевой
 * случай. Поэтому здесь ровно одно число — `price`, то самое, что крупно стоит
 * на карточке у ЭТОГО посетителя. Поля с членской ценой нет: построить из
 * карточки текст, где гость узнаёт сумму со скидкой, нельзя физически —
 * а не «нельзя по правилу в промпте».
 *
 * Процент отдаётся только словами внутри `priceNote`. Отдельное число рядом
 * с ценой делало бы `цена × (1 − процент)` естественным действием для модели.
 */
final readonly class ProductCard
{
    /**
     * @param  int|null  $price  ровно то число, что видит этот посетитель; null — «Цена по запросу»
     * @param  string  $priceNote  что стоит рядом с ценой на карточке: «уже со скидкой…» или «значок −N%…»
     * @param  string  $vatNote  «НДС 22% в том числе» — та же строка, что под ценой на сайте
     * @param  list<array{name: string, value: string}>  $specs  уже обрезаны
     * @param  string|null  $description  только когда о товаре спросили отдельно
     */
    public function __construct(
        public int $id,
        public string $name,
        public string $url,
        public string $sku,
        public string $brand,
        public bool $inStock,
        public ?int $price,
        public string $priceNote,
        public string $vatNote,
        public ?string $warranty,
        public array $specs,
        public ?string $description,
    ) {}

    /**
     * Текст карточки для результата инструмента.
     *
     * Имя товара идёт СРАЗУ ССЫЛКОЙ, а не отдельной строкой рядом. У донора
     * правило «названный товар давай со ссылкой» жило приписками в промпте
     * и в выдаче и не сработало трижды (04.09.2026): пять перфораторов
     * с ценами и гарантией, ни одной ссылки. Чтобы назвать товар без ссылки,
     * модели теперь надо разобрать разметку на части, а скопировать целиком
     * ей проще.
     */
    public function toPromptText(): string
    {
        $lines = [
            'Название: ['.$this->name.']('.$this->url.')',
            'Артикул: '.($this->sku !== '' ? $this->sku : '—'),
            'Бренд: '.($this->brand !== '' ? $this->brand : '—'),
            // Слова карточки: сайт пишет «Нет в наличии», и «под заказ» из уст
            // бота было бы обещанием поставки, которого магазин не давал.
            'Наличие: '.($this->inStock
                ? 'в наличии'
                : 'нет в наличии — срок поставки уточняет менеджер'),
            // Дословно с карточки: «12 мес.». Пусто — у 337 активных товаров
            // гарантия не заполнена, и «гарантии нет» было бы другим утверждением.
            'Гарантия производителя: '.($this->warranty ?? 'не указана на сайте — уточняет менеджер'),
            'Цена: '.$this->priceLine(),
        ];

        if ($this->specs !== []) {
            $lines[] = 'Характеристики с карточки:';

            foreach ($this->specs as $row) {
                $lines[] = '- '.$row['name'].': '.$row['value'];
            }
        }

        if ($this->description !== null && $this->description !== '') {
            // Заголовок обязателен: без него модель принимает описание
            // за продолжение списка характеристик и отвечает рекламным
            // абзацем на вопрос о числе.
            $lines[] = 'Описание товара с сайта (в нём бывают характеристики, которых нет в списке выше):';
            $lines[] = $this->description;
        }

        return implode("\n", $lines);
    }

    private function priceLine(): string
    {
        if ($this->price === null) {
            return 'на сайте стоит «Цена по запросу» — цену называет менеджер';
        }

        $line = number_format($this->price, 0, ',', ' ').' руб.';

        if ($this->vatNote !== '') {
            $line .= ' ('.$this->vatNote.')';
        }

        if ($this->priceNote !== '') {
            $line .= ' — '.$this->priceNote;
        }

        return $line;
    }
}
