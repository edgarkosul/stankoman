<?php

namespace App\Services\Ai\Data;

/**
 * Чем упорядочить выдачу поиска, когда порядок «по совпадению» не тот,
 * о чём просит покупатель.
 *
 * Появилось после разговора 5 на бою (05.10.2026). На «нужен винтовой
 * компрессор подберите дешевый» поиск отдал пятёрку по релевантности —
 * ряд Metal Master MC от 125 972 ₽, — а бот назвал её «самыми доступными».
 * В каталоге в тот момент стояли в наличии HITCOM за 93 150, LTT за 100 050
 * и CrossAir за 102 337. Инструмент не умел «дешевле», и единственным
 * способом добраться до них был УГАДАННЫЙ потолок цены.
 *
 * ⚠️ Сортировка у Meilisearch — правило ранга, а не замена ему: она стоит
 * ПОСЛЕ слов, опечаток, близости и атрибута, то есть упорядочивает товары
 * внутри групп одинаково подходящих, а не весь каталог. На «винтовой
 * компрессор» это даёт «Винтовой компрессор CrossAir…» впереди, но
 * «Компрессор винтовой HITCOM…» (другой порядок слов — другая группа)
 * остаётся ниже, хотя он дешевле. Поэтому выдача с сортировкой — это
 * «самое дешёвое из подходящего», а не «самое дешёвое в каталоге», и
 * говорит она о себе именно так.
 */
enum ProductSort: string
{
    case PriceAsc = 'price_asc';

    case PriceDesc = 'price_desc';

    /** Правило сортировки Meilisearch: поле `price` объявлено сортируемым в config/scout.php. */
    public function rule(): string
    {
        return match ($this) {
            self::PriceAsc => 'price:asc',
            self::PriceDesc => 'price:desc',
        };
    }

    /** Как подписать порядок в выдаче, чтобы модель не выдала его за другой. */
    public function label(): string
    {
        return match ($this) {
            self::PriceAsc => 'порядок: сначала ДЕШЁВЫЕ — но это самое дешёвое ИЗ ПОДХОДЯЩЕГО '
                .'под запрос, а не самый дешёвый товар каталога',
            self::PriceDesc => 'порядок: сначала ДОРОГИЕ — но это самое дорогое ИЗ ПОДХОДЯЩЕГО '
                .'под запрос, а не самый дорогой товар каталога',
        };
    }

    public static function tryFromInput(mixed $value): ?self
    {
        return is_string($value) ? self::tryFrom(trim($value)) : null;
    }
}
