<?php

namespace App\Services\Ai\Support;

/**
 * Вычищает персональные данные из текста ПЕРЕД отправкой в шлюз.
 *
 * Сначала писался не «на всякий случай» и не дублируя шлюз, а под конкретные
 * дыры, замеренные перебором 28.08.2026. Маскирование aitunnel надёжно берёт
 * email, ИНН, ОГРН, паспорт, СНИЛС, карту по контрольной сумме и ФИО с
 * отчеством.
 *
 * Не берёт шлюз три вещи, и они наши:
 *
 *   - телефон слитной записью с восьмёрки — «89211234567»;
 *   - телефон без кода страны — «921 123-45-67»;
 *   - адрес прописью — «на улице Народной, дом 12».
 *
 * С 09.10.2026 у чата есть канал deepseek — сам API DeepSeek (ChatChannels),
 * и маскирования на его стороне нет вовсе: там этот класс — единственный слой
 * между посетителем и моделью. Поэтому теперь здесь и то, что aitunnel берёт
 * сам: паспорт, СНИЛС и карта с пробелами (в [номер]), ФИО с отчеством
 * (в [имя]). Для aitunnel это второй слой — подменённое значение шлюз просто
 * не найдёт. Так же сделано в bots (f504f16, c843817).
 *
 * Плюс отдельно: на маршруте /embeddings маскирование не применяется ВООБЩЕ
 * (заголовков X-AITunnel-Masked там нет ни на одном вызове). А вопрос
 * посетителя мы эмбеддим и при поиске, и для экрана «Пробелы». Значит на
 * этом маршруте наш слой единственный, и вызывать его надо перед embed()
 * так же обязательно, как перед chat().
 *
 * ГРАНИЦА ПРИМЕНЕНИЯ. Чистим текст, написанный ПОСЕТИТЕЛЕМ. Контент магазина
 * не чистим: на странице оплаты опубликованы расчётный счёт и реквизиты,
 * и это ровно то, что бот обязан уметь продиктовать. Прогнать базу знаний
 * через редактор — значит сломать ответ на «какие у вас реквизиты» ради
 * защиты данных, которые магазин сам разместил на витрине.
 *
 * До 13.09.2026 эта граница существовала только на словах: историю разговора
 * чистили целиком, вместе с ответами самого бота. Адрес магазина, названный
 * ботом на прошлом ходу, возвращался к нему заглушкой `[email]`, и модель
 * скопировала её покупателю в новый ответ (диалог 17). Теперь граница лежит
 * в данных: у записи истории есть происхождение, и чистится всё, кроме
 * написанного нами, — см. redactIncoming().
 *
 * Имена регекспом не берутся, и делать вид, что берутся, вредно. Эта дыра
 * закрыта устройством диалога, а не текстом: контакты собираются карточкой
 * request_contact и в переписку с моделью не попадают.
 */
final class PiiRedactor
{
    public const PHONE = '[телефон]';

    public const EMAIL = '[email]';

    public const NUMBER = '[номер]';

    /**
     * ФИО с отчеством. Контактом не считается (containsContact), а в ответе
     * бота обращение по ней вырезается (withoutNamePlaceholder): «Здравствуйте,
     * [имя]!» — не повод передавать разговор менеджеру.
     */
    public const NAME = '[имя]';

    /** Все заглушки редактора. */
    public const PLACEHOLDERS = [self::EMAIL, self::PHONE, self::NUMBER, self::NAME];

    /**
     * Ключ происхождения записи истории. В шлюз не уходит — его снимает
     * withoutOrigin() перед отправкой.
     *
     * Нужен потому, что РОЛЬ происхождения не описывает: реплика живого
     * менеджера едет в модель под `assistant`, как и ответ бота, — для
     * покупателя это один собеседник. А чистить её надо, как посетительскую.
     */
    public const ORIGIN = 'origin';

    public const ORIGIN_VISITOR = 'visitor';

    public const ORIGIN_OPERATOR = 'operator';

    /** Написали МЫ: ответ бота или результат инструмента, то есть контент магазина. */
    public const ORIGIN_BOT = 'bot';

    /**
     * Телефон с кодом страны: +7, 7 или 8, дальше три цифры кода и семь цифр
     * номера с любыми разделителями либо вовсе без них.
     *
     * Границы по цифрам с обеих сторон обязательны: без них из двадцатизначного
     * номера счёта вырезался бы кусок, похожий на телефон, и остаток превращался
     * бы в мусор.
     */
    private const PATTERN_WITH_PREFIX = '/(?<!\d)(?:\+?7|8)[\s\-]?\(?\d{3}\)?[\s\-]?\d{3}[\s\-]?\d{2}[\s\-]?\d{2}(?!\d)/u';

    /**
     * Телефон без кода страны — «921 123-45-67».
     *
     * Разделители здесь ОБЯЗАТЕЛЬНЫ, и это не придирка к формату: десять цифр
     * подряд это ИНН, и без этого условия каждый ИНН превращался бы в телефон.
     */
    private const PATTERN_LOCAL = '/(?<![\d+])\(?\d{3}\)?[\s\-]\d{3}[\s\-]\d{2}[\s\-]\d{2}(?!\d)/u';

    private const PATTERN_EMAIL = '/[\p{L}0-9._%+\-]+@[\p{L}0-9.\-]+\.[\p{L}]{2,}/u';

    /**
     * Длинные цифровые серии: счета, номера карт слитно, лицевые счета.
     * Порог 12 знаков выбран так, чтобы не задеть то, что магазину нужно:
     * цены, годы, артикулы, ОГРН (13 цифр шлюз возьмёт сам, но и наш вариант
     * ему не помешает — подменённое значение он просто не найдёт).
     */
    private const PATTERN_LONG_DIGITS = '/(?<!\d)\d{12,}(?!\d)/';

    /**
     * Номер карты с пробелами или дефисами — «4276 1234 5678 9012». Слитный
     * берёт правило длинных серий. Раньше такой брал только шлюз («карта по
     * контрольной сумме»), а у самого DeepSeek маскирования нет. Кандидат —
     * от 13 до 19 цифр группами, и только с верной контрольной суммой (Луна):
     * она отсекает случайные серии вроде дат и номеров заказов.
     */
    private const PATTERN_CARD = '/(?<![\d\-])\d{4}(?:[ \-]\d{2,6}){1,5}(?![\d\-])/u';

    /**
     * СНИЛС: 3-3-3-2 — «123-456-789 01», «123 456 789 01». С локальным
     * телефоном (3-3-2-2) не путается, слитные 11 цифр не трогаем: так же
     * выглядит телефон с восьмёрки, и его берёт правило телефонов.
     */
    private const PATTERN_SNILS = '/(?<![\d\-])\d{3}[\s\-]\d{3}[\s\-]\d{3}[\s\-]+\d{2}(?![\d\-])/u';

    /**
     * Паспорт: серия и номер — «4510 123456», «45 10 123456», «4510 № 123456»,
     * «45 10 номер 123456». Разделитель между серией и номером обязателен:
     * десять цифр подряд — это ИНН компании или телефон без кода, их тут
     * трогать нельзя.
     */
    private const PATTERN_PASSPORT = '/(?<![\d\-])\d{2} ?\d{2}(?: +| *№ *| *,? *номер:? *)\d{6}(?![\d\-])/u';

    /**
     * ФИО с отчеством — в любом порядке: «Иван Петрович», «Иван Петрович
     * Сидоров», «Сидоров Иван Петрович», с падежами («Ивановичу», «Ивановной»).
     *
     * Нужно слово с заглавной рядом с отчеством: одно «Петрович» — это и
     * магазин, и обращение без имени, его не трогаем. Цена — редкие ложные
     * срабатывания вроде «Магазин Петрович» в начале фразы: лишняя заглушка
     * безопаснее имени, ушедшего в чужую страну.
     *
     * Имя без отчества («Сергей Петров») не берём — как и шлюз: ложных
     * срабатываний было бы больше, чем пользы.
     */
    private const PATTERN_FULL_NAME = '/(?<!\p{L})(?:\p{Lu}\p{Ll}+(?:-\p{Lu}\p{Ll}+)?\s+)?\p{Lu}\p{Ll}+(?:-\p{Lu}\p{Ll}+)?\s+\p{Lu}\p{Ll}+(?:(?:ович|евич|ич)(?:а|у|ем|е)?|(?:овн|евн|ичн|иничн)(?:а|ы|е|у|ой))(?:\s+\p{Lu}\p{Ll}+(?:-\p{Lu}\p{Ll}+)?)?(?!\p{L})/u';

    public function redact(string $text): string
    {
        if (trim($text) === '') {
            return $text;
        }

        // Порядок важен. Email первым: иначе цифры внутри адреса вида
        // «ivan1234567890@mail.ru» съест правило длинных серий и оставит
        // огрызок, по которому уже не видно, что это была почта.
        $text = preg_replace(self::PATTERN_EMAIL, self::EMAIL, $text) ?? $text;
        // Карта — до телефонов: куски её групп не должны стать «телефоном».
        $text = preg_replace_callback(
            self::PATTERN_CARD,
            static fn (array $m): string => self::isCardNumber($m[0]) ? self::NUMBER : $m[0],
            $text,
        ) ?? $text;
        $text = preg_replace(self::PATTERN_WITH_PREFIX, self::PHONE, $text) ?? $text;
        $text = preg_replace(self::PATTERN_LOCAL, self::PHONE, $text) ?? $text;
        $text = preg_replace(self::PATTERN_SNILS, self::NUMBER, $text) ?? $text;
        $text = preg_replace(self::PATTERN_PASSPORT, self::NUMBER, $text) ?? $text;
        $text = preg_replace(self::PATTERN_FULL_NAME, self::NAME, $text) ?? $text;

        return preg_replace(self::PATTERN_LONG_DIGITS, self::NUMBER, $text) ?? $text;
    }

    /** От 13 до 19 цифр и верная контрольная сумма по алгоритму Луна. */
    private static function isCardNumber(string $candidate): bool
    {
        $digits = preg_replace('/\D/', '', $candidate) ?? '';
        $length = strlen($digits);

        if ($length < 13 || $length > 19) {
            return false;
        }

        $sum = 0;

        for ($i = 0; $i < $length; $i++) {
            $digit = (int) $digits[$length - 1 - $i];

            if ($i % 2 === 1) {
                $digit *= 2;
                $digit = $digit > 9 ? $digit - 9 : $digit;
            }

            $sum += $digit;
        }

        return $sum % 10 === 0;
    }

    /**
     * Ответ бота без обращения по заглушке имени.
     *
     * Посетитель представился «Иван Петрович», модель увидела [имя] и пишет
     * «Здравствуйте, [имя]!». Это не контакт и не повод отдавать разговор
     * менеджеру, как при утечке [email] (ShopAssistant::leaksPlaceholder), —
     * достаточно убрать обращение: «Здравствуйте!».
     */
    public static function withoutNamePlaceholder(string $text): string
    {
        if (! str_contains($text, self::NAME)) {
            return $text;
        }

        // «[имя], подскажу…» в начале строки — убрать с запятой и вернуть заглавную.
        $text = preg_replace_callback(
            '/(^|\n)[ \t]*'.preg_quote(self::NAME, '/').'[ \t]*[,!]?[ \t]*(\p{L})?/u',
            static fn (array $m): string => $m[1].mb_strtoupper($m[2] ?? ''),
            $text,
        ) ?? $text;

        // «Здравствуйте, [имя]!» — вместе с запятой и пробелом перед ней.
        return preg_replace('/,?[ \t]*'.preg_quote(self::NAME, '/').'/u', '', $text) ?? $text;
    }

    /**
     * Прогнать исходящую историю. Роль и структура сохраняются, чистится
     * содержимое всего, ЧЬЁ ПРОИСХОЖДЕНИЕ НЕ ДОКАЗАНО: пропускаем только
     * записи с пометкой ORIGIN_BOT.
     *
     * Текст бота не чистим, и защиты это не снимает. Контакт посетителя
     * вычищен на ВХОДЕ — модель его не видела и вернуть не может. Значит
     * маскировать в её ответах нечего, а портить есть что: адрес, телефон
     * и расчётный счёт магазина, которые она продиктовала.
     *
     * Направление ошибки выбрано намеренно. Запись без пометки чистится:
     * забытая пометка обернётся лишней заглушкой в тексте бота, но не
     * утечкой реплики живого менеджера в шлюз.
     *
     * @param  list<array<string, mixed>>  $messages
     * @return list<array<string, mixed>>
     */
    public function redactIncoming(array $messages): array
    {
        foreach ($messages as $i => $message) {
            if (($message[self::ORIGIN] ?? null) === self::ORIGIN_BOT) {
                continue;
            }

            if (isset($message['content']) && is_string($message['content'])) {
                $messages[$i]['content'] = $this->redact($message['content']);
            }
        }

        return $messages;
    }

    /**
     * Сообщения в том виде, в каком их примет шлюз: своей пометки
     * происхождения он не знает и знать не должен.
     *
     * @param  list<array<string, mixed>>  $messages
     * @return list<array<string, mixed>>
     */
    public function withoutOrigin(array $messages): array
    {
        return array_map(static function (array $message): array {
            unset($message[self::ORIGIN]);

            return $message;
        }, $messages);
    }

    /** Нашлось ли в тексте что-то, что мы бы вычистили. Для телеметрии и тестов. */
    public function containsPii(string $text): bool
    {
        return $this->redact($text) !== $text;
    }

    /**
     * Есть ли в тексте КОНТАКТ — почта или телефон.
     *
     * Уже, чем containsPii(): правило длинных цифровых серий сюда не входит.
     * По этому признаку чат показывает покупателю форму контактов, а
     * двенадцатизначный артикул в вопросе — не повод просить почту.
     */
    public function containsContact(string $text): bool
    {
        if (trim($text) === '') {
            return false;
        }

        return preg_match(self::PATTERN_EMAIL, $text) === 1
            || preg_match(self::PATTERN_WITH_PREFIX, $text) === 1
            || preg_match(self::PATTERN_LOCAL, $text) === 1;
    }
}
