<?php

namespace App\Services\Ai\Tools;

/**
 * Передача разговора живому оператору.
 *
 * Инструмент только поднимает флаг и возвращает причину: всё остальное —
 * пометка «ждёт менеджера», запись в ленте, уведомления в админку, почту
 * и MAX — делает ChatEscalationService, когда ход агента закончится.
 * Разделение не формальное: инструмент вызывается в середине цикла, а
 * ход ещё может кончиться пустотой или сорваться, и будить менеджера
 * ради несостоявшегося ответа незачем.
 *
 * Статус разговора эскалация НЕ меняет: бот продолжает отвечать, пока
 * за разговор не сел человек. Почему именно так — в ChatEscalationService.
 */
final class EscalateToOperatorTool implements AssistantTool
{
    public function name(): string
    {
        return 'escalate_to_operator';
    }

    public function definition(): array
    {
        return [
            'type' => 'function',
            'function' => [
                'name' => $this->name(),
                /*
                 * «Характеристики» из перечня убраны 05.09.2026: с фазы 6A
                 * они лежат в карточке и отвечать по ним — работа бота.
                 * Описание инструмента модель читает при КАЖДОМ решении,
                 * звать ли человека, поэтому устаревшая строка здесь весила
                 * больше, чем исправленный промпт.
                 */
                'description' => 'Передать разговор менеджеру магазина. Вызывай, когда ответа '
                    .'нет ни в базе знаний, ни в карточке товара, когда вопрос о СОВМЕСТИМОСТИ '
                    .'конкретной модели, когда покупатель просит человека или недоволен. '
                    .'Характеристики и подбор передавать не нужно: характеристики есть '
                    .'в карточке, подбор делается поиском по каталогу.',
                'parameters' => [
                    'type' => 'object',
                    'properties' => [
                        'reason' => [
                            'type' => 'string',
                            'description' => 'Коротко для менеджера: о чём спрашивают и что уже выяснено.',
                        ],
                    ],
                    'required' => ['reason'],
                ],
            ],
        ];
    }

    public function run(array $arguments, ToolContext $context): string
    {
        $context->escalated = true;

        // Причина уходит менеджеру в уведомление. Обрезаем: модель иногда
        // пересказывает сюда полразговора, а в письме нужна строка темы.
        $reason = trim((string) ($arguments['reason'] ?? ''));

        if ($reason !== '') {
            $context->escalationReason = mb_substr($reason, 0, 500);
        }

        /*
         * «Ответ целиком» здесь не вежливость, а починка дефекта, найденного
         * на приёмке 04.09.2026: на «нужно сверлить отверстия 100 мм
         * в пластике» модель сделала три поиска, нашла коронки — и написала
         * покупателю одно «передал менеджеру», а следующей репликой заявила
         * «я показал подходящие по диаметру позиции», хотя не показала
         * ничего. Найденное осталось в ходе с вызовом инструмента, которого
         * покупатель не видит.
         */
        return 'Менеджер уведомлён. В СЛЕДУЮЩЕМ сообщении напиши ответ целиком: сначала '
            .'то, что ты УЖЕ нашёл (товары, условия, характеристики) — иначе покупатель '
            .'не увидит этого никогда, — и только потом, что передал вопрос менеджеру. '
            .'Написанное до вызова инструмента до покупателя не доходит. Предложи '
            .'оставить почту в форме — менеджер ответит письмом. Звонок не обещай: '
            .'телефон в той же форме есть, но он необязательный.';
    }
}
