<?php

namespace App\Services\Ai\Tools;

use App\Livewire\Common\RequestCallback;

/**
 * Показать карточку «менеджер свяжется с вами».
 *
 * Инструмент НЕ принимает контакты параметрами, и это не упущение.
 * Они вводятся в форму на стороне сайта и уходят в CallbackRequest,
 * минуя модель: контакт покупателя в переписку с провайдером не попадает
 * вообще. Дай модели поле «phone» или «email» — она начнёт их выспрашивать
 * в чате, и весь смысл потеряется.
 *
 * ПЕРЕИМЕНОВАН 07.09.2026 вместе со сменой канала. Пока инструмент
 * назывался request_callback, модель обещала звонок — не потому, что так
 * сказано в промпте, а потому что так называлась кнопка, которую она
 * нажимает. Имя инструмента для неё такой же факт, как приписка к данным,
 * и спорить с ним правилом в промпте бесполезно. Внутренности остались
 * прежними: заявка это по-прежнему CallbackRequest, и менеджер разбирает
 * её там же, где остальные, а не в отдельном «чатовом» углу.
 */
final class RequestContactTool implements AssistantTool
{
    public function name(): string
    {
        return 'request_contact';
    }

    public function definition(): array
    {
        return [
            'type' => 'function',
            'function' => [
                'name' => $this->name(),
                'description' => 'Показать покупателю форму, в которой он оставит почту, '
                    .'чтобы менеджер ответил письмом. Нужна там, где требуется ДЕЙСТВИЕ '
                    .'человека под конкретную сделку: выставить счёт на его заказ, '
                    .'посчитать доставку по адресу, подобрать модель под задачу. '
                    .'НЕ вызывай на вопрос «как это устроено» — как оплачивают юрлица, '
                    .'какие способы оплаты и доставки бывают, что с гарантией: на это '
                    .'есть база знаний, и ответить надо самому. Форму предлагают ПОСЛЕ '
                    .'ответа и вдобавок к нему, а не вместо. Контакты покупатель вводит '
                    .'сам — не спрашивай почту, телефон или имя в переписке. Говори '
                    .'о письме, а не о звонке: менеджер отвечает на почту, а телефон '
                    .'в форме необязательный, для тех, кому удобнее голосом. На «беру» '
                    .'и «хочу заказать» этот инструмент НЕ первый: сначала назови путь '
                    .'через корзину сайта, форма — вторым вариантом. Исключение — покупатель '
                    .'уже прислал контакт в сообщении (на его месте стоит [email] или '
                    .'[телефон]): тогда вызывай в этом же ходе, контакт второй раз он писать не станет. '
                    .'Кнопка «'.RequestCallback::CONTACT_BUTTON.'» появляется у покупателя только после '
                    .'вызова этого инструмента: называешь кнопку — вызови его в этом же ходе, '
                    .'не вызвал — кнопку не упоминай.',
                'parameters' => [
                    'type' => 'object',
                    'properties' => [
                        'topic' => [
                            'type' => 'string',
                            'description' => 'Тема обращения для менеджера, без персональных данных.',
                        ],
                    ],
                    'required' => ['topic'],
                ],
            ],
        ];
    }

    public function run(array $arguments, ToolContext $context): string
    {
        $context->callbackRequested = true;

        // Тема подставится в комментарий заявки: менеджер перезванивает,
        // уже понимая вопрос, и не начинает разговор с «а вы о чём?».
        $topic = trim((string) ($arguments['topic'] ?? ''));

        if ($topic !== '') {
            $context->callbackTopic = mb_substr($topic, 0, 300);
        }

        /*
         * «Сначала ответь» здесь не вежливость, а починка дефекта,
         * найденного на приёмке 03.09.2026: на «как оплатить счёт
         * юрлицу» модель вызывала этот инструмент и выдавала одно
         * «менеджер перезвонит», хотя ответ лежал в базе знаний
         * с релевантностью 0.69. Прошлый текст возврата — «скажи,
         * что менеджер перезвонит» — читался как исчерпывающая
         * инструкция к ответу.
         *
         * «Звонок» из возврата убран 13.09.2026 (диалог 17). Инструмент
         * переименовали ещё 07.09, а возврат продолжал говорить «форма
         * обратного звонка» и «перезвонит» — и модель трижды обещала
         * покупателю звонок при канале «письмо». Текст возврата она читает
         * как факт, так же как имя инструмента.
         */
        return 'Форма контактов показана: покупатель оставит в ней почту. Сама форма '
            .'на экране не видна — под перепиской стоит кнопка «'.RequestCallback::CONTACT_BUTTON.'», '
            .'поля открываются по нажатию. Направляя к форме, называй эту кнопку, а не '
            .'«форму под перепиской». В СЛЕДУЮЩЕМ '
            .'сообщении напиши ответ целиком: сначала сам ответ на вопрос, потом — что '
            .'менеджер ответит письмом. Звонок не обещай: телефон в форме необязательный, '
            .'он для тех, кому удобнее голосом. То, что ты написал до вызова этого '
            .'инструмента, покупатель не увидит, поэтому «также» и «кроме того» в начале '
            .'ответа означают, что половина ответа пропала. Контакты в переписке не спрашивай.';
    }
}
