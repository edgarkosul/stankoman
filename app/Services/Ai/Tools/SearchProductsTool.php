<?php

namespace App\Services\Ai\Tools;

use App\Services\Ai\Contracts\ProductLookup;
use App\Services\Ai\Data\ProductCard;
use App\Services\Ai\Data\ProductMatches;
use App\Services\Ai\Data\ProductQuery;
use App\Services\Catalog\CatalogBrands;
use App\Services\Catalog\CatalogQueryShape;
use Illuminate\Support\Facades\Log;
use Throwable;

/**
 * Поиск товара в каталоге: название, артикул, бренд, с фильтрами по цене,
 * наличию, разделу и типу техники.
 *
 * Индекс отвечает на «что похоже на запрос», цена и остаток приходят
 * из базы (ProductLookup).
 *
 * ЧЕГО ЗДЕСЬ НЕТ ПРОТИВ ДОНОРА, и почему.
 *
 * Отбора по числовой характеристике (`spec`, `spec_min`, `spec_max`) нет
 * намеренно. У kratonshop характеристики лежат в EAV и заполнены почти
 * у всех; у нас EAV покрывает треть каталога, а «Мощность» заполнена
 * у 514 товаров из 2 576. Фильтр выглядел бы работающим и молча прятал
 * 80% каталога — хуже, чем не фильтровать вовсе. Вернуть можно только
 * с порогом заполненности внутри раздела и припиской в выдаче.
 *
 * Смыслового поиска пока нет — это фаза 8, зеркало `products_semantic`.
 * До неё поиск идёт по словам, и описание инструмента говорит именно это:
 * донорская формулировка «передавай запрос словами покупателя, поиск сам
 * сопоставит по смыслу» появилась у него вместе с зеркалом, а без зеркала
 * она обещает то, чего нет, — «компрессор для гаража» словами найдёт
 * «гаражные» чехлы, а не компрессор. Вернуть её вместе с фазой 8.
 */
final class SearchProductsTool implements AssistantTool
{
    private const LIMIT = 5;

    /** Сколько разделов идёт в фильтр по типу техники. */
    private const SECTIONS_FOR_TYPE = 4;

    public function __construct(
        private readonly ProductLookup $products,
        private readonly CatalogBrands $brands,
    ) {}

    public function name(): string
    {
        return 'search_products';
    }

    public function definition(): array
    {
        return [
            'type' => 'function',
            'function' => [
                'name' => $this->name(),
                'description' => 'Найти товары магазина по названию, артикулу, модели или бренду, '
                    .'с отбором по цене, наличию и разделу. Поиск идёт по СЛОВАМ в названии, '
                    .'артикуле и бренде товара: передавай то, что стоит в названии, — вид '
                    .'техники, бренд, модель («ленточнопильный станок», «компрессор Hansmann», '
                    .'«BSM-115»). Описание задачи («для гаража», «чем резать трубу») поиск '
                    .'по словам не понимает: переведи его в вид техники. Бренд, написанный '
                    .'кириллицей, передавай как есть — поиск сам переведёт его в латиницу. '
                    .'Возвращает наличие, цену, ссылку и характеристики с карточки — '
                    .'их достаточно, чтобы назвать разницу между найденным. Полное '
                    .'описание одного товара берётся отдельно, через get_product.',
                'parameters' => [
                    'type' => 'object',
                    'properties' => [
                        'query' => [
                            'type' => 'string',
                            'description' => 'Вид техники, бренд, модель или артикул — слова, '
                                .'которые стоят в названии товара.',
                        ],
                        'in_stock' => [
                            'type' => 'boolean',
                            'description' => 'Только то, что есть в наличии.',
                        ],
                        'price_min' => ['type' => 'integer', 'description' => 'Цена от, руб.'],
                        'price_max' => ['type' => 'integer', 'description' => 'Цена до, руб.'],
                        'category_id' => [
                            'type' => 'integer',
                            'description' => 'Искать только внутри раздела каталога. Номер '
                                .'раздела даёт browse_categories — сначала спроси покупателя, '
                                .'какой раздел ему ближе.',
                        ],
                        'section' => [
                            'type' => 'string',
                            'description' => 'ТИП техники словом покупателя: «винтовой», '
                                .'«ленточнопильный», «ручной», «полуавтоматический». Поиск сам '
                                .'найдёт подходящие разделы каталога и сузит выдачу до них. '
                                .'Ставь всегда, когда покупатель назвал тип: в названиях '
                                .'товаров тип обычно не пишут, он есть только в разделе.',
                        ],
                    ],
                    'required' => ['query'],
                ],
            ],
        ];
    }

    public function run(array $arguments, ToolContext $context): string
    {
        if ($context->alreadyCalled($this->name(), $arguments)) {
            return 'Такой вызов в этом ходе уже был, и повтор ничего нового не вернёт. '
                .'Ответь покупателю по тому, что уже нашлось, или измени запрос.';
        }

        $query = trim((string) ($arguments['query'] ?? ''));

        if ($query === '') {
            return 'Пустой запрос. Уточни у покупателя, какой товар он ищет.';
        }

        $typeDropped = false;

        try {
            $section = $this->sectionFor($query, $arguments, $context);
            $sectionIds = $this->sectionIds($section, $query);

            $search = fn (array $ids): ProductMatches => $this->products->search(new ProductQuery(
                text: $query,
                seesDiscounts: $context->seesDiscounts,
                inStockOnly: ($arguments['in_stock'] ?? null) === true,
                priceMin: is_numeric($arguments['price_min'] ?? null) ? (int) $arguments['price_min'] : null,
                priceMax: is_numeric($arguments['price_max'] ?? null) ? (int) $arguments['price_max'] : null,
                categoryId: is_numeric($arguments['category_id'] ?? null) ? (int) $arguments['category_id'] : null,
                sectionIds: $ids,
                limit: self::LIMIT,
            ));

            $matches = $search($sectionIds);

            /*
             * Фильтр по типу не дал ничего — ищем ещё раз без него.
             *
             * «Ничего не нашлось» по вине нашего же фильтра — худший из
             * возможных ответов: бот скажет покупателю, что товара нет,
             * и тот уйдёт к тому, у кого «есть». Пустой результат от фильтра
             * по типу отличить от пустого каталога можно только здесь: модель
             * фильтр не ставила и снять его не может.
             *
             * Что тип не применён, выдача говорит вслух — иначе бот выдаст
             * найденное за технику названного типа.
             */
            $typeDropped = $matches->cards === [] && $sectionIds !== [];

            if ($typeDropped) {
                $matches = $search([]);
            }
        } catch (Throwable $e) {
            Log::warning('Поиск товаров для ассистента не ответил', ['error' => $e->getMessage()]);

            return 'Поиск по каталогу временно недоступен. Предложи связаться с менеджером.';
        }

        $cards = $matches->cards;

        if ($cards === []) {
            return $this->nothingFound($matches);
        }

        foreach ($cards as $card) {
            $context->noteCard($card);
        }

        if (! $context->seesDiscounts) {
            $context->withholdPrices($this->products->memberPrices(array_map(
                static fn (ProductCard $card): int => $card->id,
                $cards,
            )));
        }

        /*
         * Вся выдача не в наличии — это отдельный факт, и покупатель должен
         * узнать его от бота, а не сам заметить в конце разговора. У донора
         * 04.09.2026 на «компрессор в бюджете 300–400 тысяч» бот выдал три
         * позиции под заказ, при том что в этом бюджете один стоял на складе.
         */
        $outOfStock = array_filter($cards, static fn (ProductCard $card): bool => $card->inStock) === [];

        /*
         * Выдача обязана сама рассказывать, чем она ограничена. У донора
         * 04.09.2026 модель сделала поиск БЕЗ фильтров и поиск с бюджетом,
         * а потом смешала обе выдачи и подписала их «в вашем бюджете» —
         * с товаром дешевле вилки в списке. Результаты разных поисков лежат
         * в контексте рядом и ничем не различаются, если не подписать их.
         */
        $applied = [];

        if (is_numeric($arguments['price_min'] ?? null)) {
            $applied[] = 'цена от '.number_format((int) $arguments['price_min'], 0, ',', ' ').' ₽';
        }

        if (is_numeric($arguments['price_max'] ?? null)) {
            $applied[] = 'цена до '.number_format((int) $arguments['price_max'], 0, ',', ' ').' ₽';
        }

        if (($arguments['in_stock'] ?? null) === true) {
            $applied[] = 'только в наличии';
        }

        if (is_numeric($arguments['category_id'] ?? null)) {
            $applied[] = 'раздел №'.(int) $arguments['category_id'];
        }

        if ($section !== '') {
            $applied[] = $typeDropped
                ? 'тип «'.$section.'» НЕ применён — в разделах этого типа ничего не нашлось, '
                    .'и выдача собрана без него; не выдавай найденное за технику этого типа, '
                    .'если это не видно из названия, и скажи покупателю, что именно такого '
                    .'типа не нашлось'
                : 'тип «'.$section.'»';
        }

        /*
         * Подпись о смене алфавита появилась у донора по той же причине, что
         * и приписка ниже: без неё модель ОТРИЦАЛА собственную выдачу. На
         * «Компрессор хансман» инструмент вернул пять Hansmann, а бот ответил
         * «таких моделей не нашлось» — он не связал кириллицу вопроса с
         * латиницей данных и решил, что поиск подсунул похожее. Подпись
         * описывает данные, а не политику: что искали и почему написание
         * разошлось, — вывод «это тот же бренд» уже следует из неё.
         *
         * Текст подписи — тот, что РЕАЛЬНО ушёл в индекс: с написанием бренда
         * вместо прочтения («сталекс» → stalex), а не буквальная транслитерация.
         */
        $script = preg_match('/\p{Cyrillic}/u', $query) === 1 && $matches->searchedText !== ''
            ? ' (искали в латинской записи «'.$matches->searchedText
                .'», потому что бренды в каталоге пишутся латиницей: бренд, написанный'
                .' в выдаче латиницей, и его кириллическое написание в вопросе —'
                .' ОДИН И ТОТ ЖЕ бренд, а не замена ему)'
            : '';

        $scope = 'из каталога (это ТОЛЬКО САМЫЕ ПОДХОДЯЩИЕ, а не весь список: '
            .'не говори «в ассортименте всего столько-то» и «есть только одна модель» — '
            .'ты этого не знаешь) по запросу «'.$query.'»'.$script
            .($applied === [] ? ', без фильтров' : ', фильтры: '.implode(', ', $applied))
            .'. Говори о цене и бюджете только по ЭТОЙ выдаче: результаты прошлых'
            .' поисков в этом же ходе были получены с другими условиями.';

        $note = $outOfStock
            ? ' ВНИМАНИЕ: всего найденного НЕТ В НАЛИЧИИ. Скажи об этом покупателю прямо'
                .' и предложи поискать то, что есть в наличии (in_stock: true).'
            : '';

        /*
         * Выдача собрана без части слов — и модель обязана это знать. Иначе
         * «электропитбайк white siberia belluga», по которому поиск отдал
         * электромотоциклы White Siberia, она подаст как точный ответ.
         * Витрина над такой выдачей пишет «Не нашлось: …»; бот говорит то же.
         */
        $relaxed = $matches->relaxed
            ? ' ВНИМАНИЕ: '.self::quoted($matches->unmatched).' — таких слов нет ни в одном товаре каталога,'
                .' и выдача собрана БЕЗ НИХ, по остальным словам запроса. Скажи покупателю прямо,'
                .' что именно '.self::quoted($matches->unmatched).' не нашлось, и не выдавай найденное'
                .' за то, что он просил.'
            : '';

        /*
         * Приписка рядом с данными, а не только правилом в промпте: модель
         * охотно читает мощность и объём из названия модели, и факт о том,
         * чего в данных НЕТ, работает надёжнее запрета абзацем выше. Помечена
         * служебной явно — без пометки модель пересказывала её покупателю
         * лекцией о цифрах в названиях.
         *
         * Правило донора на будущее: приписка к данным описывает данные,
         * а не политику, и переписывается вместе с ними. У него устаревшая
         * приписка «характеристик в этих данных нет» перебивала исправленный
         * промпт, потому что стояла рядом с данными и весила больше.
         */
        return 'Найдено '.count($cards).' '.$scope
            .' Имя каждого товара дано готовой ссылкой — переноси его в ответ'
            .' целиком, вместе со ссылкой: без неё покупателю некуда нажать.'.$note.$relaxed."\n\n"
            .implode("\n\n", array_map(static fn (ProductCard $card): string => $card->toPromptText(), $cards))
            ."\n\nСЛУЖЕБНОЕ, покупателю не пересказывать и не объяснять: "
            .'характеристики бери ТОЛЬКО из строк «Характеристики с карточки» '
            .'и из описания, если оно здесь показано. Цифры в названии модели '
            .'характеристикой НЕ являются: «BSM-115» — это имя, а не размер. '
            .'Нужного параметра в списке нет — не решай, что его нет в магазине: '
            .'вызови get_product по артикулу, в полной карточке все характеристики '
            .'и описание. Совместимость — единственное, чего в данных нет совсем: '
            .'такой вопрос передавай менеджеру.';
    }

    /**
     * Пустая выдача — со словами, которых в каталоге нет, если они известны.
     *
     * Такое слово чаще всего — вид техники, названный не так, как в каталоге:
     * «бензогенератор» против «Генератор бензиновый». Сказать это модели —
     * значит дать ей шанс на второй поиск, а не на «такого у нас нет».
     */
    private function nothingFound(ProductMatches $matches): string
    {
        $unknown = $matches->unmatched === []
            ? ''
            : ' Слов '.self::quoted($matches->unmatched).' нет ни в одном товаре: если это вид'
                .' техники, назови его так, как пишут в названиях товаров, и поищи ещё раз.';

        return 'В каталоге ничего не нашлось по этому запросу.'.$unknown.' Не предполагай, что товар '
            .'есть: уточни название или передай вопрос менеджеру.';
    }

    /**
     * @param  list<string>  $words
     */
    private static function quoted(array $words): string
    {
        return implode(', ', array_map(static fn (string $word): string => '«'.$word.'»', $words));
    }

    /**
     * Тип техники, применяемый к этому поиску, — с тремя оговорками донора.
     *
     * ПЕРВАЯ: тип «липкий» в пределах хода. Назвал его один раз — он держится
     * до конца, даже если в следующем вызове модель про него забыла. У донора
     * на «поршневой компрессор в наличии, 300–400 тысяч» модель сделала два
     * поиска — с типом без бюджета и с бюджетом без типа — и по второму
     * сообщила, что поршневых нет. Правилом в промпте это не чинилось.
     *
     * ВТОРАЯ: к запросу-обозначению тип не применяется вовсе. Артикул уникален,
     * сужение по типу может только потерять его, а липкость делала промах
     * неисправимым — сбросить фильтр модель не может, она его не ставила.
     *
     * ТРЕТЬЯ: к запросу с БРЕНДОМ тоже. Бренд сужает выдачу сильнее любого
     * типа; тип поверх бренда способен только отнять (см. CatalogBrands).
     *
     * @param  array<string, mixed>  $arguments
     */
    private function sectionFor(string $query, array $arguments, ToolContext $context): string
    {
        if (CatalogQueryShape::looksLikeModel($query)) {
            return '';
        }

        if ($this->brands->mentionedIn($query) !== null) {
            return '';
        }

        return trim((string) ($arguments['section'] ?? '')) ?: $this->rememberedSection($context);
    }

    /**
     * Разделы, до которых сужает тип техники.
     *
     * Тип ищется ВМЕСТЕ с запросом, а не отдельным словом, как у донора,
     * и это замер 15.09.2026 на своём каталоге. Донорские типы («поршневой»,
     * «винтовой») в его дереве почти уникальны, а наше «ручной» стоит
     * в четырёх разделах, ни один из которых не про станки: «Аппараты ручной
     * лазерной сварки», «Арматурогибы ручные», «Ручные гидравлические
     * насосы», «Арматурорезы ручные». Настоящий раздел «Ручные
     * ленточнопильные станки» — 141 товар — не попадал в четвёрку вовсе,
     * и поиск «ленточнопильный станок» с типом «ручной» возвращал пустоту.
     *
     * Вместе с запросом развилка решается сама: раздел обязан содержать
     * ВСЕ слова («ручн» + «ленточнопильн» + «стан»), и остаётся ровно нужный.
     * Не нашлось ничего — второй заход одним типом, как у донора: это лучше,
     * чем потерять тип совсем.
     *
     * @return list<int>
     */
    private function sectionIds(string $section, string $query): array
    {
        if ($section === '') {
            return [];
        }

        foreach ([trim($section.' '.$query), $section] as $phrase) {
            $ids = array_map(
                static fn ($found): int => $found->id,
                $this->products->sections($phrase, self::SECTIONS_FOR_TYPE),
            );

            if ($ids !== []) {
                return $ids;
            }
        }

        return [];
    }

    private function rememberedSection(ToolContext $context): string
    {
        foreach (array_reverse($context->calls) as $call) {
            if (($call['name'] ?? null) !== $this->name()) {
                continue;
            }

            $section = trim((string) (($call['arguments'] ?? [])['section'] ?? ''));

            if ($section !== '') {
                return $section;
            }
        }

        return '';
    }
}
