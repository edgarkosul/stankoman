<?php

namespace App\Services\Catalog;

/**
 * Что за запрос пришёл: модель с артикулом или человеческая формулировка.
 *
 * Нужно ради одного числа — доли смысла в гибридном поиске. Замер
 * 04.09.2026 на живом каталоге показал, что одного порога на все запросы
 * не существует:
 *
 *   «на дачу пол пылесосить»   0.3 хуже, 0.5 и 0.8 одинаково хороши
 *   «компрессор для гаража»    0.3 даёт промывочный компрессор и шланг
 *   «ВК-J 15/10»               до 0.3 точная модель первая; на 0.5 хвост
 *                              засоряется ножами и токарным станком;
 *                              на 0.8 модель теряется совсем
 *
 * Причина понятна: артикул — это последовательность знаков, а не смысл.
 * «ВК-J 15/10» и «ВК-J 15/8» для вектора почти одно и то же, а для
 * покупателя это разные машины и разные деньги.
 *
 * Отсюда правило: там, где в запросе видна модель, смысл почти выключаем
 * и полагаемся на буквы; там, где человек описывает задачу, — наоборот.
 */
final class CatalogQueryShape
{
    /**
     * Похоже ли на модель или артикул.
     *
     * Признаков три, и все проверяются только на КОРОТКОМ запросе — до
     * четырёх слов. Порог отсекает описания задачи с числами внутри:
     * «компрессор до 30 тысяч для гаража» моделью не является, хотя
     * цифра там есть.
     *
     *   1. цифра вместе с латиницей или разделителем — «VK41001510»,
     *      «15/10», «DM-7500B»;
     *   2. латиница вместе с разделителем, даже без единой цифры, —
     *      «WDK-DUSTER», «EP+». Требование цифры первым вариантом этого
     *      правила и было исходной ошибкой: половина серий в каталоге
     *      называется буквами;
     *   3. голый числовой артикул из пяти и более цифр. Пять — граница,
     *      ниже которой начинаются мощности, объёмы и напряжения:
     *      «2200», «380», «100».
     */
    public static function looksLikeModel(string $query): bool
    {
        $query = trim($query);

        if ($query === '') {
            return false;
        }

        $words = preg_split('/\s+/u', $query) ?: [];

        if (count($words) > 4) {
            return false;
        }

        foreach ($words as $word) {
            $hasDigit = preg_match('/\d/u', $word) === 1;
            $hasLatin = preg_match('/[A-Za-z]/', $word) === 1;
            $hasSeparator = preg_match('~[/\-+.]~u', $word) === 1;

            if ($hasDigit && ($hasLatin || $hasSeparator)) {
                return true;
            }

            if ($hasLatin && $hasSeparator) {
                return true;
            }
        }

        return count($words) === 1 && preg_match('/^\d{5,}$/', $query) === 1;
    }

    /**
     * Голая суть обозначения: только буквы и цифры, в нижнем регистре.
     *
     * «ВК-J 15/10 TG», «ВК J15/10TG» и «вкj1510tg» — это одна и та же
     * машина, записанная тремя способами, и покупатель пользуется всеми
     * тремя. Разделители в обозначениях техники стоят как придётся, и
     * сравнивать строки целиком бессмысленно.
     */
    public static function core(string $text): string
    {
        return mb_strtolower((string) preg_replace('/[^\p{L}\p{N}]+/u', '', $text));
    }

    /**
     * Тот ли это товар, который покупатель назвал.
     *
     * Проверка нарочно строгая: обозначение целиком должно найтись
     * в названии или совпасть с артикулом. Похожесть здесь не годится —
     * ВК-J 15/10 и ВК-J 15/8 отличаются одной цифрой, стоят разных денег
     * и подходят разным задачам.
     *
     * Порог в четыре знака отсекает мусор вроде «TG» и «15», который
     * найдётся в половине каталога.
     */
    public static function namesProduct(string $query, string $name, string $sku = ''): bool
    {
        $core = self::core($query);

        if (mb_strlen($core) < 4) {
            return false;
        }

        return $core === self::core($sku)
            || mb_strpos(self::core($name), $core) !== false;
    }
}
