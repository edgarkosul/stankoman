<?php

namespace App\Services\Chat;

/**
 * Сколько ждать между опросами сервера — чистая функция от состояния чата.
 *
 * Главный риск виджета не в модели, а в воркерах FPM на проде: каждый
 * тик поллинга — это `/livewire/update`, то есть полноценный PHP-процесс.
 * Виджет, опрашивающий сервер раз в две секунды у сотни открытых вкладок,
 * кладёт витрину раньше, чем кончается бюджет на модель. Поэтому лесенка,
 * а не постоянный интервал.
 *
 * Пороги взяты из замера донора, а не назначены: p50 ответа 5.6 с, p95 34 с,
 * максимум 58 с. Первые полминуты укладывается больше половины ответов —
 * там оправданы две секунды. К девяноста секундам приходит практически
 * всё, дальше опрос идёт только чтобы не потерять припозднившийся ответ.
 *
 * Отдельным классом, а не парой ветвей в компоненте: это часть виджета,
 * которую можно проверить тестом без базы и без сети.
 */
final class ChatPollingCadence
{
    /** Быстрая фаза: сюда попадает больше половины ответов. */
    public const FAST_UNTIL_SECONDS = 30;

    /** Средняя фаза: к её концу приходит практически всё. */
    public const MEDIUM_UNTIL_SECONDS = 90;

    /**
     * Дальше опрашивать бессмысленно: джоба живёт 200 секунд, после чего
     * её хук failed() сам напишет посетителю ответ. Не написал даже он —
     * значит, задачу никто не взял, и ждать больше нечего: панель пишет
     * мягкую эскалацию и отпускает поллинг.
     *
     * Кнопки «Обновить» здесь нет намеренно. К этой секунде ответ либо уже
     * есть, либо не появится никогда, — кнопка не могла бы принести ничего,
     * кроме перекладывания нашей аварии на покупателя.
     */
    public const GIVE_UP_AFTER_SECONDS = 210;

    /**
     * Как часто лаунчер спрашивает «мне не ответили?», пока панель свёрнута.
     *
     * Здесь можно быть щедрее, чем в панели: тик стоит маленький JSON
     * от обычного контроллера, а не `/livewire/update` с рендером
     * компонента. Но и спешить некуда — ждут тут ответа человека.
     */
    public const LAUNCHER_INTERVAL_SECONDS = 20;

    /**
     * Дольше получаса одна вкладка не опрашивает.
     *
     * Оставленная на ночь страница не должна стучать до утра, а потеря
     * невелика: ответ, пришедший позже, покажет бейдж на следующей
     * открытой странице — его считает сервер при отрисовке.
     */
    public const LAUNCHER_STOPS_AFTER_SECONDS = 1800;

    /**
     * Вопрос у человека — ждать можно долго, и это нормальное состояние
     * разговора, а не сбой. Два часа: дальше посетитель почти наверняка
     * уже ушёл со страницы, на которой писал.
     */
    public const LAUNCHER_WATCHES_STAFF_SECONDS = 7200;

    /**
     * Отвечает бот — счёт на секунды. Пяти минут хватает с запасом даже
     * на умершую джобу: её хук failed() пишет заглушку к 200-й секунде,
     * а это тоже сообщение, и бейдж на него встанет.
     */
    public const LAUNCHER_WATCHES_BOT_SECONDS = 300;

    /**
     * На двадцатой секунде ожидания индикатор «печатает» меняется на
     * «Секунду, уточняю…». Это не украшение: разброс латентности сидит
     * на стороне шлюза и убрать его нельзя, а 14% ответов идут дольше
     * пятнадцати секунд. Без этой смены посетитель решает, что чат завис.
     */
    public const THINKING_HINT_AFTER_SECONDS = 20;

    /**
     * Есть ли чего ждать при свёрнутой панели.
     *
     * Гейт нужен не ради красоты. Кука чата вечная, и разговор никто
     * не закрывает: без ограничения посетитель, однажды написавший в чат,
     * опрашивал бы сервер на каждой странице до конца времён.
     */
    public static function launcherWatches(
        bool $escalated,
        bool $operatorLed,
        int $secondsSinceLastMessage,
    ): bool {
        $window = ($escalated || $operatorLed)
            ? self::LAUNCHER_WATCHES_STAFF_SECONDS
            : self::LAUNCHER_WATCHES_BOT_SECONDS;

        return $secondsSinceLastMessage >= 0 && $secondsSinceLastMessage <= $window;
    }

    /**
     * @param  bool  $awaitingReply  ответ бота готовится прямо сейчас
     * @param  int  $waitedSeconds  сколько уже ждём
     * @param  bool  $panelOpen  панель развёрнута на экране
     * @param  bool  $operatorLed  разговор ведёт живой оператор
     * @param  bool  $escalated  вопрос передан менеджеру
     * @return string|null интервал для wire:poll или null — не опрашивать
     */
    public static function interval(
        bool $awaitingReply,
        int $waitedSeconds,
        bool $panelOpen,
        bool $operatorLed = false,
        bool $escalated = false,
    ): ?string {
        if ($awaitingReply) {
            return match (true) {
                $waitedSeconds >= self::GIVE_UP_AFTER_SECONDS => null,
                $waitedSeconds < self::FAST_UNTIL_SECONDS => '2s',
                $waitedSeconds < self::MEDIUM_UNTIL_SECONDS => '5s',
                default => '10s',
            };
        }

        /*
         * Панель свёрнута — сюда мы не попадаем: `wire:poll.visible`
         * в скрытом элементе не тикает, и компонент об этом состоянии
         * не узнаёт. Свёрнутый чат сторожит лаунчер (`launcherWatches`),
         * и делает это дешевле — маленьким JSON вместо рендера Livewire.
         */
        if (! $panelOpen) {
            return null;
        }

        /*
         * Разговор ведёт человек. Четыре секунды, а не восемь: здесь
         * показывается «менеджер печатает ответ…», и признак набора живёт
         * секунды — на редком тике он мигал бы или не появлялся вовсе.
         */
        if ($operatorLed) {
            return '4s';
        }

        /*
         * Вопрос передан менеджеру, но за разговор он ещё не сел. Именно
         * в этом состоянии оператор впервые берёт разговор и впервые пишет,
         * и посетитель должен увидеть это, а не узнать через минуту.
         */
        if ($escalated) {
            return '8s';
        }

        /*
         * Открытая панель без ожидания. У донора здесь стоял null — и это
         * была ошибка, найденная на живой проверке: пока панель не опрашивает
         * сервер, до неё не доходит НИЧЕГО, что происходит на другой стороне.
         *
         * Цена тика при этом почти нулевая: ChatPanel::poll() сверяет
         * отпечаток состояния и на неизменившемся делает skipRender().
         */
        return '10s';
    }

    /** Пора менять «печатает» на «секунду, уточняю…». */
    public static function showsThinkingHint(int $waitedSeconds): bool
    {
        return $waitedSeconds >= self::THINKING_HINT_AFTER_SECONDS;
    }

    /** Ждать больше нечего. */
    public static function givenUp(int $waitedSeconds): bool
    {
        return $waitedSeconds >= self::GIVE_UP_AFTER_SECONDS;
    }
}
