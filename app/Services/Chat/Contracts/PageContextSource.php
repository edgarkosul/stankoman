<?php

namespace App\Services\Chat\Contracts;

use Illuminate\Http\Request;

/**
 * Где стоит посетитель — в виде, который не стыдно показать модели.
 *
 * Шов между чатом и витриной: что такое «карточка товара», «раздел каталога»
 * и «страница», и какую цену видит этот посетитель, знает магазин
 * (App\Shop\ShopPageContext), а не чат.
 *
 * Работа разбита на два шага, и это не дробление ради дробления.
 *
 * `locate()` вызывается при КАЖДОМ показе страницы, поэтому не делает
 * ни одного запроса к базе: он лишь снимает с маршрута локатор («карточка,
 * слаг такой-то»). Любой запрос здесь умножился бы на весь трафик витрины.
 *
 * `describe()` вызывается в момент ОТПРАВКИ сообщения, то есть на порядки
 * реже, и уже ходит в базу за свежими ценой и наличием. Заодно это снимает
 * главную ошибку раннего снимка: цена, взятая при загрузке страницы,
 * к моменту вопроса успевает устареть.
 *
 * Формат структуры и её перевод в строки промпта — App\Services\Chat\PageContext.
 */
interface PageContextSource
{
    /**
     * Локатор страницы или null, если страница не из белого списка.
     *
     * Белый список узкий намеренно. Каталог и информационные страницы — да;
     * корзина, оформление заказа и личный кабинет — нет: там на экране лежат
     * персональные данные и содержимое заказа, которым в переписке со шлюзом
     * делать нечего.
     *
     * @return array<string, string>|null
     */
    public function locate(Request $request): ?array;

    /**
     * Локатор, развёрнутый в структуру для `chat_messages.page_context`.
     *
     * Контекст страницы — украшение, а не условие работы: любая ошибка
     * здесь означает «отвечаем без контекста», но не «сообщение не ушло».
     *
     * @param  array<string, string>|null  $locator
     * @param  bool  $seesDiscounts  цена — та, что крупно стоит на карточке у этого посетителя
     * @return array<string, mixed>|null
     */
    public function describe(?array $locator, bool $seesDiscounts): ?array;
}
