<?php

namespace App\Services\Kb\Contracts;

use App\Services\Kb\Data\KbDocument;

/**
 * Поставщик контента для базы знаний.
 *
 * Каждый источник отвечает за свой набор документов и помечает их своим
 * именем (`name()`), чтобы источник можно было переиндексировать или снести
 * целиком, не задевая остальные.
 *
 * Это одна из границ, отделяющих движок ассистента от конкретного магазина.
 * Код между источником и хранилищем общий с kratonshop; сами источники —
 * свои: у intertooler страницы хранят HTML, а реквизиты живут в настройках.
 */
interface KbSource
{
    /** Короткое имя источника, попадает в колонку `source`. */
    public function name(): string;

    /**
     * Все документы источника, пригодные к индексации.
     *
     * @return iterable<KbDocument>
     */
    public function documents(): iterable;
}
