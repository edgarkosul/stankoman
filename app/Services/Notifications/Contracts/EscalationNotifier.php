<?php

namespace App\Services\Notifications\Contracts;

/**
 * Канал доставки пуша об эскалации.
 *
 * Отдельным интерфейсом, потому что мессенджер — вещь сменная: сегодня MAX,
 * завтра заказчик захочет что-то ещё, а джоба уведомлений об этом знать
 * не должна. Источником истины ни один такой канал не является: им остаётся
 * уведомление в самой админке, которое не зависит ни от чьего API.
 */
interface EscalationNotifier
{
    /** Канал настроен и им можно пользоваться. */
    public function isConfigured(): bool;

    /**
     * Отправить короткое сообщение со ссылкой на диалог.
     *
     * Возвращает успех, но НЕ бросает: сбой мессенджера не должен ронять
     * джобу, из-за которой не уйдёт письмо.
     */
    public function send(string $text, ?string $url = null): bool;
}
