<?php

namespace App\Shop;

/**
 * Понятные названия строк характеристик, которые поставщик пишет загадкой.
 *
 * Metal Master и REALREZ у ленточных и торцовочных пил пишут сечение
 * заготовки, которую станок режет под углом, строкой «90° (мм)» —
 * значение «400 / 400×400» (круг / прямоугольник). Покупатель о такой
 * строке спрашивает словами «заготовка 400 на 400» или «пропил под 45»,
 * и модель, подбирая по порогу (`find_by_spec`), не узнавала в «90° (мм)»
 * то, что ищет: в диалоге Эдгара 09.10.2026 MGH-400E, BS 400 CH и MGH-400
 * не находились, пока строку не называла сама подсказка (реестр bots 10.1).
 *
 * Только для бота: на карточке витрины строка остаётся такой, какой её
 * прислал поставщик.
 */
final class SupplierSpecNames
{
    /**
     * Угол, затем необязательные «(П)»/«(Л)», «(мм)» или «, мм», затем
     * необязательная зеркальная пара «/ -60° (мм)» и хвост в скобках.
     */
    private const ANGLE = '/^(-?\d{1,2})\s*[°º˚](?:\s*\(([ПЛ])\))?\s*(?:\(мм\)|,\s*мм)?'
        .'(\s*\/\s*-\1\s*[°º˚]\s*(?:\(мм\)|,\s*мм)?)?\s*(\([^)]*\))?$/u';

    public static function readable(string $name): string
    {
        $clean = trim(str_replace("\u{00AD}", '', $name));

        if (preg_match(self::ANGLE, $clean, $match) !== 1) {
            return $name;
        }

        $angle = (($match[3] ?? '') !== '' ? '±' : '').$match[1].'°';

        $side = match ($match[2] ?? '') {
            'П' => ' вправо',
            'Л' => ' влево',
            default => '',
        };

        $note = ($match[4] ?? '') !== '' ? ' '.$match[4] : '';

        return 'Сечение заготовки под '.$angle.$side.$note.', мм';
    }
}
