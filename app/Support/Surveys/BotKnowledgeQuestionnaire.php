 * Вопросы владельцу магазина перед запуском ИИ-помощника в чате.
 *
 * Бот отвечает только тем, что магазин о себе написал, а где написано мало —
 * додумывает. Проверка 16.09.2026 на 29 вопросах покупателей: 11 ответов
 * сочинены (адрес магазина выдан за сервисный центр, «кредит или лизинг»,
 * «работаем по договору поставки»). Лечится не настройкой, а фактами
 * от владельца — их и собирает эта анкета.
 *
 * Схема одна на три места: страницу в админке (варианты, поля, превью ответа
 * бота), проверку ответов на сервере и выгрузку `survey:bot-knowledge`.
 * Поэтому здесь нет разметки — только данные.
 *
 * Поле `says` — фраза, которой бот передаст выбранный вариант покупателю.
 * Из них страница на лету собирает превью ответа, а выгрузка — черновик
 * будущей статьи. `{value}` подставляется из текстового поля, `{list}` —
 * из отмеченных пунктов. Факты во фразах только те, что владелец выбрал
 * или вписал сам: превью, обещающее больше анкеты, учило бы тому же,
 * от чего анкета лечит.
 *
 * Ответы хранятся так: [id вопроса => [id поля => значение]]. Выбор — ключ
 * варианта, отметки — список ключей, текст — строка; у отметок с «другим»
 * рядом лежит `<id>_other`, у каждого вопроса — свободный `note`.
 */
