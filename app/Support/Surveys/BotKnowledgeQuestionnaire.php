    /**
     * @param  list<array<string, mixed>>  $options
     * @return array<string, mixed>
     */
    private static function choice(string $id, string $label, array $options): array
    {
        return ['type' => 'choice', 'id' => $id, 'label' => $label, 'options' => $options];
    }

    /**
     * @param  list<array<string, mixed>>  $options
     * @param  array{0: string, 1: list<string>}|null  $showIf
     * @return array<string, mixed>
     */
    private static function multi(string $id, string $label, array $options, string $says, ?string $other = null, ?array $showIf = null): array
    {
        return array_filter([
            'type' => 'multi',
            'id' => $id,
            'label' => $label,
            'options' => $options,
            'says' => $says,
            'other' => $other,
            'showIf' => $showIf === null ? null : ['field' => $showIf[0], 'in' => $showIf[1]],
        ], static fn (mixed $value): bool => $value !== null);
    }

    /**
     * @param  array{0: string, 1: list<string>}|null  $showIf
     * @return array<string, mixed>
     */
    private static function text(string $id, string $label, string $placeholder = '', ?string $says = null, ?array $showIf = null, int $rows = 2): array
    {
        return array_filter([
            'type' => 'text',
            'id' => $id,
            'label' => $label,
            'placeholder' => $placeholder,
            'says' => $says,
            'rows' => $rows,
            'showIf' => $showIf === null ? null : ['field' => $showIf[0], 'in' => $showIf[1]],
        ], static fn (mixed $value): bool => $value !== null);
    }

    /**
     * @return array<string, string>
     */
    private static function opt(string $key, string $title, ?string $says = null): array
    {
        return array_filter(
            ['key' => $key, 'title' => $title, 'says' => $says],
            static fn (?string $value): bool => $value !== null,
        );
    }

    /** @return list<string> */
    private static function optionKeys(array $field): array
    {
        return array_column($field['options'], 'key');
    }

    /** @return array<string, string>|null */
    private static function option(array $field, mixed $key): ?array
    {
        foreach ($field['options'] as $option) {
            if ($option['key'] === $key) {
                return $option;
            }
        }

        return null;
    }

    private static function cleanText(mixed $value): string
    {
        if (! is_string($value)) {
            return '';
        }

        // Управляющие символы из вставленного текста — мусор, переносы строк — нет.
        $value = preg_replace('/[^\P{C}\n\t]/u', '', $value) ?? '';

        return mb_substr(trim($value), 0, self::TEXT_LIMIT);
    }

    private static function filled(mixed $value): bool
    {
        return is_array($value) ? $value !== [] : trim((string) $value) !== '';
    }
