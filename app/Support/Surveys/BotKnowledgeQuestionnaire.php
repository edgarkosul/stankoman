    /**
     * Оставляет от присланного только то, что анкета умеет спрашивать:
     * известные вопросы и поля, существующие варианты, видимые при этих
     * ответах поля, текст в пределах потолка.
     *
     * Скрытое поле выбрасывается, а не хранится: «адрес своего сервиса»,
     * вписанный до переключения на «сервис производителя», — уже неправда.
     *
     * @param  array<mixed>  $input
     * @return array<string, array<string, string|list<string>>>
     */
    public static function sanitize(array $input): array
    {
        $clean = [];

        foreach (self::questions() as $question) {
            $given = $input[$question['id']] ?? null;

            if (! is_array($given)) {
                continue;
            }

            $values = [];

            foreach ($question['fields'] as $field) {
                if (! self::visible($field, $values)) {
                    continue;
                }

                $raw = $given[$field['id']] ?? null;

                if ($field['type'] === 'choice') {
                    if (is_string($raw) && in_array($raw, self::optionKeys($field), true)) {
                        $values[$field['id']] = $raw;
                    }

                    continue;
                }

                if ($field['type'] === 'multi') {
                    $picked = is_array($raw) ? array_values(array_filter($raw, 'is_string')) : [];
                    $keys = array_values(array_intersect(self::optionKeys($field), $picked));

                    if ($keys !== []) {
                        $values[$field['id']] = $keys;
                    }

                    if (isset($field['other'])) {
                        $other = self::cleanText($given[$field['id'].'_other'] ?? null);

                        if ($other !== '') {
                            $values[$field['id'].'_other'] = $other;
                        }
                    }

                    continue;
                }

                $text = self::cleanText($raw);

                if ($text !== '') {
                    $values[$field['id']] = $text;
                }
            }

            $note = self::cleanText($given[self::NOTE] ?? null);

            if ($note !== '') {
                $values[self::NOTE] = $note;
            }

            if ($values !== []) {
                $clean[$question['id']] = $values;
            }
        }

        return $clean;
    }

    /**
     * Отвечен ли вопрос. Один комментарий не считается: он дополняет ответ,
     * но по нему не видно, что выбор сделан.
     *
     * @param  array<string, mixed>  $answers  ответы на этот вопрос
     */
    public static function isAnswered(array $question, array $answers): bool
    {
        foreach ($question['fields'] as $field) {
            if (! self::visible($field, $answers)) {
                continue;
            }

            if (self::filled($answers[$field['id']] ?? null) || self::filled($answers[$field['id'].'_other'] ?? null)) {
                return true;
            }
        }

        return false;
    }

    /**
     * @param  array<string, array<string, mixed>>  $answers
     */
    public static function answeredCount(array $answers): int
    {
        $count = 0;

        foreach (self::questions() as $question) {
            if (self::isAnswered($question, $answers[$question['id']] ?? [])) {
                $count++;
            }
        }

        return $count;
    }

    /**
     * Что бот скажет покупателю по этим ответам — те же правила, что у превью
     * на странице (`reply()` в шаблоне). Разойтись они не должны: владелец
     * одобряет то, что видит.
     *
     * @param  array<string, mixed>  $answers  ответы на этот вопрос
     */
    public static function botReply(array $question, array $answers): ?string
    {
        $parts = [];

        foreach ($question['fields'] as $field) {
            if (! self::visible($field, $answers)) {
                continue;
            }

            $value = $answers[$field['id']] ?? null;

            if ($field['type'] === 'choice') {
                $says = self::option($field, $value)['says'] ?? null;

                if (is_string($says)) {
                    $parts[] = $says;
                }

                continue;
            }

            if (! isset($field['says'])) {
                continue;
            }

            if ($field['type'] === 'multi') {
                $titles = [];

                foreach ((array) $value as $key) {
                    $titles[] = self::option($field, $key)['title'] ?? $key;
                }

                $other = $answers[$field['id'].'_other'] ?? null;

                if (self::filled($other)) {
                    $titles[] = $other;
                }

                if ($titles !== []) {
                    $parts[] = str_replace('{list}', implode(', ', $titles), $field['says']);
                }

                continue;
            }

            if (self::filled($value)) {
                $parts[] = str_replace('{value}', rtrim((string) $value, '. '), $field['says']);
            }
        }

        return $parts === [] ? null : implode(' ', $parts);
    }

    /**
     * Ответы человеческим текстом — для разработчика, который по ним пишет статьи.
     *
     * @param  array<string, array<string, mixed>>  $answers
     */
    public static function toMarkdown(array $answers): string
    {
        $lines = [];
        $sections = array_column(self::sections(), 'title', 'id');
        $currentSection = null;

        foreach (self::questions() as $number => $question) {
            if ($question['section'] !== $currentSection) {
                $currentSection = $question['section'];
                $lines[] = '';
                $lines[] = '## '.$sections[$currentSection];
            }

            $given = $answers[$question['id']] ?? [];

            $lines[] = '';
            $lines[] = '### '.($number + 1).'. '.$question['title'];

            if (! self::isAnswered($question, $given) && ! self::filled($given[self::NOTE] ?? null)) {
                $lines[] = '_нет ответа_';

                continue;
            }

            foreach ($question['fields'] as $field) {
                if (! self::visible($field, $given)) {
                    continue;
                }

                $value = $given[$field['id']] ?? null;
                $shown = match ($field['type']) {
                    'choice' => self::option($field, $value)['title'] ?? null,
                    'multi' => implode(', ', array_filter([
                        ...array_map(fn (string $key): string => self::option($field, $key)['title'] ?? $key, (array) $value),
                        $given[$field['id'].'_other'] ?? null,
                    ])),
                    default => $value,
                };

                if (self::filled($shown)) {
                    $lines[] = '- '.$field['label'].': '.$shown;
                }
            }

            if (self::filled($given[self::NOTE] ?? null)) {
                $lines[] = '- Комментарий: '.$given[self::NOTE];
            }

            $reply = self::botReply($question, $given);

            if ($reply !== null) {
                $lines[] = '';
                $lines[] = '> Бот: '.$reply;
            }
        }

        return ltrim(implode("\n", $lines))."\n";
    }

    /**
     * @param  array<string, mixed>  $values  уже принятые ответы этого вопроса
     */
    public static function visible(array $field, array $values): bool
    {
        if (! isset($field['showIf'])) {
            return true;
        }

        $current = $values[$field['showIf']['field']] ?? null;

        return is_string($current) && in_array($current, $field['showIf']['in'], true);
    }

