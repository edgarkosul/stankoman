<?php

declare(strict_types=1);

/*
|--------------------------------------------------------------------------
| Бот магазина — то, что принадлежит магазину, а не движку
|--------------------------------------------------------------------------
|
| Движок бота — пакет siteko/chatbot (реестр bots 10.3): шлюз, модель,
| база знаний, потолки чата, сроки хранения и эскалация настраиваются его
| конфигом `chatbot.*` (vendor/siteko/chatbot/config/chatbot.php), под теми
| же переменными окружения `AI_*`, что и раньше. Два ключа, в которых магазин
| расходится с умолчаниями пакета, — в `config/chatbot.php`.
|
| Здесь — только своё: зеркало каталога со смыслом, страницы сайта в базе
| знаний, кука токена разговора, свои хосты и предпросмотр виджета.
|
| Всё, что берётся из env, обязано читаться через config() в коде: на проде
| конфиг кэшируется, и прямой getenv() там ведёт себя иначе.
|
*/

return [
    /*
    |--------------------------------------------------------------------------
    | Смысловой поиск по каталогу
    |--------------------------------------------------------------------------
    |
    | Векторы товаров живут в ОТДЕЛЬНОМ зеркале `products_semantic`, а не
    | в витринном `stankoman_products`. Это не вкусовщина: Meilisearch
    | с объявленным эмбеддером `userProvided` отвергает документ без вектора
    | целиком, а Scout шлёт документы пачками и про векторы не знает —
    | любой новый товар и вся пачка импорта выпадали бы из поиска ВИТРИНЫ
    | до ближайшей ночи. Витринный индекс эмбеддер не объявляет.
    |
    | Гибридный поиск даёт одним запросом и слова, и смысл, и фильтры
    | по цене, наличию и разделу. Для артикулов это важнее чистых векторов:
    | «ВК-J 15/10 TG» требует точного совпадения, «для гаража» — смысла.
    |
    */
    'catalog_search' => [
        /*
         * Зеркальный индекс и имя эмбеддера в его настройках. Лежат здесь,
         * а не строками в трёх местах: меняются они вместе.
         */
        'index' => (string) env('AI_CATALOG_INDEX', 'products_semantic'),
        'embedder' => (string) env('AI_CATALOG_EMBEDDER', 'shop'),

        /*
         * Потолок текста, уходящего в вектор. У донора 1200 знаков покрывали
         * средний разобранный текст товара целиком. У нас описания длиннее
         * (медиана 1 310 знаков против донорских 1 301 на весь текст), так
         * что обрезка коснётся половины каталога — но обрезается ХВОСТ,
         * а в начале собранного текста стоят название, бренд и
         * характеристики, то есть то, по чему и ищут. Пересмотреть после
         * первых живых замеров выдачи.
         */
        'text_limit' => max(200, (int) env('AI_CATALOG_TEXT_LIMIT', 1200)),

        /*
         * Доля смысла в гибриде: 0 — только слова, 1 — только вектор.
         */
        'semantic_ratio' => max(0.0, min(1.0, (float) env('AI_CATALOG_SEMANTIC_RATIO', 0.5))),

        /*
         * Доля смысла для запроса-обозначения: артикул, модель, НАЗВАНИЕ
         * БРЕНДА. Замер донора на «ВК-J 15/10»: до 0.3 точная модель держится
         * первой, на 0.5 хвост засоряется чужими товарами, на 0.8 модель
         * теряется совсем.
         *
         * Бренд попал в ту же корзину дорогой ценой (kratonshop, 09.09.2026):
         * на «Харсман есть?» слова находили Hansmann в обоих индексах, но
         * попадание с одной опечаткой стоит 0.494, а вектор выдуманного слова
         * давал случайному товару 0.783 — при доле 0.5 побеждал алмазный круг,
         * и бот отвечал, что бренда в каталоге нет. Дело не в пороге,
         * а в несравнимости шкал: 0.78 здесь не сходство, а шумовой пол,
         * «Квазимодо» получает 0.750 против того же товара.
         *
         * Ноль не ставим — небольшая примесь смысла подтягивает соседние
         * исполнения той же серии, а это как раз то, что покупателю полезно.
         */
        'semantic_ratio_model' => max(0.0, min(1.0, (float) env('AI_CATALOG_SEMANTIC_RATIO_MODEL', 0.2))),

        /*
         * Сколько товаров эмбеддить за один вызов шлюза. Вынесено отдельно
         * от общего размера партии: здесь тексты длиннее фрагментов базы.
         */
        'batch' => max(1, (int) env('AI_CATALOG_EMBED_BATCH', 32)),
    ],

    /*
    |--------------------------------------------------------------------------
    | Страницы сайта в базе знаний
    |--------------------------------------------------------------------------
    */
    'knowledge_base' => [
        /*
         * Страницы сайта, попадающие в базу знаний. Список, а не «все
         * подряд»: в базе должно лежать то, что отвечает на вопросы,
         * а не витринные тексты.
         *
         * Чем это не косметика — замер донора. Страница «Отгрузки» (галерея
         * прошлых поставок) давала 11% корпуса, но всплывала в топ-3 у ШЕСТИ
         * вопросов из 24 и занимала первое место у трёх — включая «какая
         * погода в москве». Ответить она не может ни на один: близость
         * возникает по словам «компрессор», «станок», «поставка». Для бота
         * это худший вид шума — он не приводит к отказу, он даёт
         * правдоподобный на вид контекст, на котором строится неверный ответ.
         *
         * Список ниже собран по замеру своих страниц 10.09.2026 (16
         * опубликованных, из них шесть пустые — 7 байт, `<p></p>`):
         *
         *   dostavka-i-oplata  1 269 знаков текста — доставка, оплата, сроки
         *   o-kompanii         2 004 — кто мы, чем занимаемся
         *   kontakty             614 — адрес, реквизиты, телефон, почта
         *   production           701 — сварка ленточных пил на ЧПУ, полотна
         *                              под размер: это услуга, а не витрина,
         *                              и на вопрос «сварите под мой станок»
         *                              отвечает по существу
         *   service              503 — что делает поддержка: подбор запчастей
         *                              и аналогов, инструкции, гарантия
         *
         * Кого сюда НЕ берём и почему:
         *
         *   sertifikaty-i-licenzii — 122 знака текста: одна фраза «является
         *       дилером более чем ста производителей» и дальше картинки.
         *       Это ровно донорский случай: фрагмент выиграет выдачу на
         *       «сертификат» и «официальный дилер», не ответив ничего.
         *       Появится текст — вернём;
         *   terms, privacy — юридические простыни на 9,5 тысяч знаков каждая,
         *       вдвое длиннее всего полезного корпуса. Они выиграют выдачу
         *       на «возврат», «гарантия», «оплата», и бот зачитает
         *       нецитируемый юридический текст вслух;
         *   home, novosti, karera — витрина, пустышки и вакансии: покупателя
         *       не касаются;
         *   arenda-oborudovaniia, dokumenty, remont-texniki, servisnyi-centr,
         *   sotrudniki — пустые страницы.
         *
         * Итого ~5 100 знаков ≈ 6–8 фрагментов. Донор считал тонким корпус
         * из 27. Это и есть главный риск проекта: базу знаний надо ПИСАТЬ,
         * а не собирать.
         */
        'static_pages' => [
            'dostavka-i-oplata',
            'o-kompanii',
            'kontakty',
            'production',
            'service',
        ],
    ],

    /*
    |--------------------------------------------------------------------------
    | Виджет на витрине
    |--------------------------------------------------------------------------
    |
    | Посетитель анонимен, и опознаёт его единственный секрет — токен диалога
    | в вечной httpOnly-куке, которую ставит СЕРВЕР. Не localStorage: в
    | переписке может оказаться телефон, а токен даёт к ней доступ — из
    | localStorage его унесёт любой XSS. Плюс Safari режет срок жизни кук,
    | выставленных из JS, до семи дней, а серверные httpOnly не режет.
    |
    */
    'chat' => [
        'cookie' => env('AI_CHAT_COOKIE', 'intertooler_chat'),

        /*
         * Хосты магазина: с них ссылка в ленте остаётся кликабельной,
         * как со своей витрины (`site.hosts` пакета, см. ShopSettingsStore).
         *
         * Список ЗАКРЫТЫЙ и правится только разработчиком: в нём вся защита
         * от подписи-обманки «[Оплатить заказ](http://evil.ru)». Нужен он
         * сверх APP_URL потому, что на деве APP_URL — это localhost:8103,
         * и проверять поведение ссылок на стенде, где оно другое, значит
         * проверять не то.
         */
        'own_hosts' => array_values(array_filter(array_map(
            'trim',
            explode(',', (string) env('AI_CHAT_OWN_HOSTS', 'intertooler.ru,www.intertooler.ru')),
        ))),

        /*
         * Предпросмотр: виджет выкачен, но виден не всем.
         *
         * Нужен, чтобы код приехал на настоящий сайт раньше, чем виджет
         * увидят покупатели: заказчик смотрит на живом каталоге, а не на
         * копии, где товары вчерашние. Он же канареечный выкат.
         *
         * Сотрудники магазина видят виджет всегда. Остальные — по ссылке
         * `?bot=<ключ>`, которая запоминается кукой на год.
         *
         * Пустой ключ при включённом предпросмотре означает «никому»,
         * а не «всем»: забытая настройка не должна открывать виджет молча.
         */
        'preview' => [
            'enabled' => filter_var(env('AI_CHAT_PREVIEW', false), FILTER_VALIDATE_BOOL),
            'key' => (string) env('AI_CHAT_PREVIEW_KEY', ''),
        ],
    ],

];
