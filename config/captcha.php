<?php

/*
|--------------------------------------------------------------------------
| Защита форм от роботов
|--------------------------------------------------------------------------
|
| Провайдер один — Яндекс SmartCaptcha, и выбран он не по вкусу: reCAPTCHA
| с апреля 2026 живёт по условиям Google Cloud (проект с принятым соглашением
| плюс привязанный биллинг), а Google Cloud не обслуживает клиентов из России,
| то есть привести ключ в соответствие магазину нечем.
|
| Что это значит по существу: SmartCaptcha — челлендж, а не скоринг. Даже
| в невидимом режиме подозрительному показывается задание, а ответ бинарный,
| без оттенков. Поэтому порогов здесь нет и быть не может.
|
| Переключатель `driver` оставлен не «на будущее»: со значением `null` он
| отключает проверку вместе с чтением ключей, и это единственный способ
| погасить капчу без выката, если сервис начнёт заворачивать живых
| покупателей.
|
*/

return [

    /*
    | smartcaptcha | null
    |
    | null отдаёт заглушку, которая пропускает всё, — это режим разработки:
    | с включённой проверкой домена токен с localhost всё равно не пройдёт,
    | и без заглушки чат на деве оказался бы наглухо закрыт.
    */
    'driver' => env('CAPTCHA_DRIVER', 'smartcaptcha'),

    /*
    | Рубильник. По умолчанию капча живёт только на проде — там и только там
    | есть домен, на который выписаны ключи.
    |
    | `testing` в этом списке быть не должно: тест, забывший выключить
    | проверку, молча ушёл бы в сеть к Яндексу. Тому единственному тесту,
    | которому капча нужна как предмет проверки, она включается сама.
    */
    'enabled' => env('CAPTCHA_ENABLED', env('APP_ENV') === 'production'),

    'drivers' => [

        'smartcaptcha' => [
            'site_key' => env('SMARTCAPTCHA_CLIENT_KEY', ''),   // ysc1_…, уходит в браузер
            'secret_key' => env('SMARTCAPTCHA_SERVER_KEY', ''), // ysc2_…, только на сервере

            'js_url' => 'https://smartcaptcha.cloud.yandex.ru/captcha.js',
            'validate_url' => 'https://smartcaptcha.cloud.yandex.ru/validate',

            // Невидимый режим: кнопки «я не робот» нет, проверка запускается
            // при отправке. Обычный покупатель не видит ничего, задание
            // достаётся только подозрительным. В форме создания капчи этого
            // параметра нет вовсе — он живёт только здесь, в коде виджета.
            'invisible' => true,

            /*
            | Блок «Защищено SmartCaptcha» в углу экрана.
            |
            | Прячем — но взамен обязаны уведомить посетителя сами, и плашка
            | под полем ввода именно за этим. Это не косметика, а требование
            | условий использования сервиса.
            |
            | Прячем потому, что блок висит в углу ЭКРАНА, а не формы: на
            | витрине он налезал бы на кнопку чата.
            */
            'hide_shield' => true,

            'language' => 'ru',

            // Столько же, сколько у DaData: дольше держать посетителя на
            // кнопке нельзя, а fail-open в верификаторе делает таймаут
            // неопасным.
            'timeout' => 4.0,

            /*
            | Режим отладки: задание показывается ВСЕМ и всегда.
            |
            | Единственный способ увидеть худший сценарий глазами — как
            | головоломка ложится поверх панели чата и что происходит, когда
            | её закрывают крестиком. На проде переменной нет, то есть false,
            | и так и должно быть.
            */
            'test' => (bool) env('SMARTCAPTCHA_TEST', false),
        ],
    ],
];
