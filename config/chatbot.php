<?php

/*
|--------------------------------------------------------------------------
| Пакет siteko/chatbot — то, в чём магазин расходится с его умолчаниями
|--------------------------------------------------------------------------
|
| Остальной конфиг пакета — у него (vendor/siteko/chatbot/config/chatbot.php):
| пакет сливает свой файл с этим по ключам верхнего уровня, и ключ отсюда
| заменяет его ключ целиком. Поэтому здесь только два ключа, и каждый
| полностью.
|
*/

return [

    /*
    | Магазин — всегда один сайт, номер 1 (так данные приняла миграция
    | `adopt_chatbot_package`). В `.env` строка `CHATBOT_SITE_ID=1` тоже
    | стоит, но не единственная защита: пакет без сайта роняет и чат,
    | и админку бота (`MissingSiteContext`), и забытая при переезде строка
    | окружения не должна этого стоить.
    */
    'site_id' => is_numeric(env('CHATBOT_SITE_ID')) ? (int) env('CHATBOT_SITE_ID') : 1,

    /*
    | Основы обычных слов, которые нечёткое сравнение путает с брендами
    | нашего каталога. Замер 15.09.2026: без списка 15 ложных «брендов» на
    | 134 обычных вопросах — «стали» → Stalex, «металла» → MetalMaster,
    | «сверла» → Everlast, «зерно» → Zero. Причина в окончаниях, а не
    | в пороге: «стали» отстоит от «stalex» на одну замену, как «харсман»
    | от «hansmann». Узнав «бренд», поиск снимает фильтр по типу техники,
    | то есть «станок для резки металла» терял бы тип там, где он нужнее
    | всего. У пакета по умолчанию список пуст.
    |
    | Сравнивается по НАЧАЛУ слова, поэтому основы хватает на все падежи.
    | Новый поставщик с именем-словом — сюда, после прогона CatalogBrandsTest
    | пакета на нашем списке брендов.
    */
    'catalog' => [
        'brand_lookalikes' => array_values(array_filter(array_map(
            'trim',
            explode(',', (string) env('AI_CATALOG_BRAND_LOOKALIKES', 'стал,металл,сверл,зерн')),
        ))),
    ],

];
