import { captchaToken } from '../modules/captcha';

/**
 * Кнопка отправки формы, защищённой капчей.
 *
 * Контракт с сервером простой: компонент всегда зовёт `submitWithToken`,
 * даже когда токена нет. Нужен он или нет, решает сервер, и разметке об
 * этом знать незачем.
 *
 * Предзагрузку компонент на себя не берёт: у каждой формы свой момент,
 * когда её пора начинать. Панель чата грузит скрипт при отрисовке формы
 * ввода, модалка витрины — при открытии; сделай это в init() безусловно,
 * и 124 КБ поехали бы на каждой карточке товара. Триггер остался
 * в разметке, рядом с формой, где его видно (window.captchaPreload).
 *
 * Конфиг бывает двух видов. Формам витрины его можно передать аргументом:
 * он не меняется, пока форма на экране. Чату — атрибутом `data-captcha`
 * на корне компонента, и читается он в момент нажатия. Причина в том, что
 * Livewire при перерисовке переносит в новую разметку уже живой
 * Alpine-компонент, и аргумент из x-data остаётся таким, каким был при
 * первой отрисовке, а атрибуты обновляются. У чата капча включается посреди
 * жизни формы: посетитель очистил переписку или менеджер закрыл диалог.
 * Со старым конфигом на руках форма отправляла бы пустой токен, и сервер
 * отказывал бы до перезагрузки страницы.
 *
 * @param {{enabled: boolean, siteKey: string}|null} config
 * @param {string} method — метод Livewire-компонента, принимающий токен
 */
export default (config = null, method = 'submitWithToken') => ({
    busy: false,

    currentConfig() {
        // Не $root: у чата send() зовут и из поля ввода по Enter, а у поля
        // свой x-data, и $root там — само поле, без атрибута.
        const live = this.$el.closest('[data-captcha]')?.dataset.captcha;

        return live ? JSON.parse(live) : config;
    },

    async send() {
        // Двойной клик не должен превращаться во второй вопрос боту.
        if (this.busy) return;

        this.busy = true;

        try {
            // Ждём и отправку тоже: без await кнопка освобождалась бы сразу
            // после отсылки, и второй клик успевал бы проскочить до того,
            // как wire:loading повесит disabled.
            await this.$wire[method](await captchaToken(this.currentConfig()));
        } finally {
            // Именно finally: если сервер вернул ошибку, посетитель обязан
            // иметь возможность нажать снова.
            this.busy = false;
        }
    },
});
