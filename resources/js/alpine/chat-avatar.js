/**
 * Лицо бота в шапке панели чата.
 *
 * Отдельный компонент, а не кусок chat-launcher: панель — Livewire, и её
 * разметка живёт своей жизнью. Два следствия, оба существенные.
 *
 * Первое: коробку аватара обязательно оборачивать в `wire:ignore`. Маскот
 * вставляется в DOM скриптом, а Livewire на каждом опросе сверяет дерево
 * с серверным и всё лишнее вычищает — робот пропадал бы через несколько
 * секунд после открытия чата, без единой ошибки в консоли.
 *
 * Второе: монтировать надо из самой панели, а не снаружи. Панель грузится
 * лениво и появляется в DOM тогда, когда её открыли; к этому моменту
 * лаунчер давно отработал свой init.
 *
 * @param {number} [size] сторона коробки в CSS-пикселях
 */
export default (size = 40) => ({
    mascot: null,

    init() {
        import('../mascot/mascot-loader.js').then(({ shouldLoadMascot, attachCalmMascot }) => {
            if (!shouldLoadMascot()) return;

            return attachCalmMascot(this.$el, size).then((controller) => {
                this.mascot = controller;
            });
        });
    },

    destroy() {
        // Панель могут закрыть и открыть заново. Оставленный экземпляр
        // продолжал бы крутить кадры и слушать курсор в пустоту.
        this.mascot?.destroy();
        this.mascot = null;
    },
});
