it('подставляет написание бренда вместо его прочтения', function () use ($catalog): void {
    $cases = [
        'сталекс' => 'stalex',
        'вактул' => 'vactool',
        'вактуль' => 'vactool',
        'эфко' => 'efco',
        'кроссэйр' => 'crossair',
        'кросэйр' => 'crossair',
        'метмашин' => 'metmachine',
        'спитценрайтер' => 'spitzenreiter',
        'шпитценрайтер' => 'spitzenreiter',
        'декси' => 'dexi',
        'кселерон' => 'xeleron',
        'варриор' => 'warrior',
        'компрессор кроссэйр 50 литров' => 'kompressor crossair 50 litrov',
        'Станок Сталекс' => 'stanok stalex',
        'лазер метмашин 1500' => 'lazer metmachine 1500',
        'осушитель спитценрайтер' => 'osusitel\' spitzenreiter',
        'пылесос вактул' => 'pylesos vactool',
        'триммер эфко' => 'trimmer efco',
    ];

    foreach ($cases as $query => $expected) {
        expect(BrandSpelling::substitute($query, $catalog))->toBe($expected, "«{$query}»");
    }
});

it('латиницу не трогает, даже если она написана «как слышится»', function () use ($catalog): void {
    // Покупатель, набравший латиницу, уже выбрал написание, и в ней бывают артикулы.
    expect(BrandSpelling::substitute('staleks', $catalog))->toBe('staleks')
        ->and(BrandSpelling::substitute('efco tn', $catalog))->toBe('efco tn')
        ->and(BrandSpelling::substitute('Hansmann CD-65F', $catalog))->toBe('Hansmann CD-65F');
});

it('бренды из нескольких слов и с дефисом не подставляет', function () use ($catalog): void {
    // «техник» не должен становиться Tech-Nick, «корвет» — Энкор Корвет.
    expect(BrandSpelling::substitute('техник', $catalog))->toBe('tehnik')
        ->and(BrandSpelling::substitute('айрон мак', $catalog))->toBe('ajron mak');
});

it('известные и принятые потери', function () use ($catalog): void {
    /*
     * Ironmac («айронмак»), Bycon («байкон»), EVOline («эволайн»), JULI
     * («джули») читаются по-английски, а свёртка английской фонетики не знает.
     * Правило под каждый — это новые совпадения с русскими словами ради
     * запроса, которого в логах 05–15.09.2026 не было ни разу.
     */
    expect(BrandSpelling::substitute('айронмак', $catalog))->toBe('ajronmak')
        ->and(BrandSpelling::substitute('байкон', $catalog))->toBe('bajkon')
        ->and(BrandSpelling::substitute('эволайн', $catalog))->toBe('evolajn');
});

