<?php

use App\Services\Ai\Support\ReplyFormatter;
use Tests\TestCase;

/*
 * Приложение поднимается ради одной строки: выброс иероглифов пишется
 * в лог, а фасад лога без контейнера не работает. Раньше файл обходился
 * без загрузки — цена в миллисекундах, и она того стоит: молчаливая
 * чистка ответа хуже отсутствующей.
 */
uses(TestCase::class);

$format = fn (string $text): string => (new ReplyFormatter)->format($text);

// Разметку с фазы 3.10 разбирает ChatMarkdown, и снятие звёздочек отсюда
// удалено вместе с регекспами. Здесь остались обороты про внутреннюю кухню
// и то, что текст в остальном не трогается.

it('оставляет разметку модели нетронутой', function () use ($format): void {
    // Раньше эти строки чистились регекспами. Теперь их разбирает парсер
    // в ленте, а формат — не его дело: снятие разметки здесь означало бы
    // потерю ссылок и списков ровно там, ради чего 3.10 и делалась.
    $text = "Цена **402 659 руб.**\n\n- по счёту\n- картой\n\n[Карточка товара](https://intertooler.ru/p/1)";

    expect($format($text))->toBe($text);
});

it('прячет упоминания внутренней кухни, сохраняя грамматику', function () use ($format): void {
    // Замена, а не вырезание: фраза стоит в середине предложения.
    expect($format('В базе знаний магазина указано, что действует гарантия.'))
        ->toBe('У нас указано, что действует гарантия.')
        ->and($format('К сожалению, в базе знаний нет информации о рассрочке.'))
        ->toBe('К сожалению, у нас нет информации о рассрочке.')
        ->and($format('Согласно найденной информации, доставка бесплатна.'))
        ->toBe('По нашим данным, доставка бесплатна.');
});

it('прячет базу знаний в любом падеже и с опечаткой модели', function () use ($format): void {
    // Приёмка 14.09.2026: «В база знаний указано» — модель ошиблась в падеже,
    // а фильтр сверял одну форму буква в букву и промолчал.
    expect($format('Да, отправляем и СДЭКом тоже. В база знаний указано, что отгрузка возможна.'))
        ->toBe('Да, отправляем и СДЭКом тоже. У нас указано, что отгрузка возможна.')
        ->and($format('По базе знаний отгрузка возможна.'))->toBe('По нашим данным отгрузка возможна.')
        ->and($format('Согласно базе знаний, доставка бесплатна.'))->toBe('По нашим данным, доставка бесплатна.')
        ->and($format('Из базы знаний: гарантия 12 месяцев.'))->toBe('По нашим данным: гарантия 12 месяцев.')
        ->and($format('Я проверил базу знаний, там этого нет.'))->toBe('Я проверил наши данные, там этого нет.')
        ->and($format('В нашей базе знаний этого нет.'))->toBe('У нас этого нет.')
        ->and($format('У меня нет доступа к базе знаний.'))->toBe('У меня нет доступа к нашим данным.')
        ->and($format('Ответа нет в базе знаний сайта.'))->toBe('Ответа нет у нас.');
});

it('выбрасывает прикидку доставки через разницу в цене', function () use ($format): void {
    // Приёмка 14.09.2026, дважды: разницу в цене бот выдавал за стоимость
    // доставки и сводил суммы в пользу чужого магазина.
    expect($format('У нас дешевле — 96 450 руб. Разница с предложением за 105 000 руб. может как раз покрыть доставку до Ярославля. Генератор есть на складе.'))
        ->toBe('У нас дешевле — 96 450 руб. Генератор есть на складе.')
        ->and($format("Цена у нас ниже.\n\nРазница около 8 500 ₽ — примерно на эти деньги и выйдет перевозка транспортной компанией."))
        ->toBe('Цена у нас ниже.')
        // Жирная цена и ссылка в том же ответе переживают выброс.
        ->and($format('Цена **96 450 руб.** Разница с **105 000 руб.** покроет доставку. Подробнее — [Способы оплаты](https://intertooler.ru/page/dostavka-i-oplata).'))
        ->toBe('Цена **96 450 руб.** Подробнее — [Способы оплаты](https://intertooler.ru/page/dostavka-i-oplata).');
});

it('не трогает условия доставки и разницу в цене по отдельности', function () use ($format): void {
    expect($format('Доставка до терминала ТК бесплатна при заказе от 30 000 руб.'))
        ->toBe('Доставка до терминала ТК бесплатна при заказе от 30 000 руб.')
        ->and($format('Разница в цене — 8 550 руб. в нашу пользу.'))
        ->toBe('Разница в цене — 8 550 руб. в нашу пользу.');
});

it('не трогает «знания» без «базы»', function () use ($format): void {
    expect($format('Специальные знания для монтажа не нужны.'))->toBe('Специальные знания для монтажа не нужны.');
});

it('не трогает слово «база» в обычном смысле', function () use ($format): void {
    expect($format('Компрессор на базе винтового блока.'))->toBe('Компрессор на базе винтового блока.');
});

it('выбрасывает иероглифы, попавшие в русский ответ', function (): void {
    // Найдено на приёмке 04.09.2026: «Если эта цена超出了 ваш бюджет».
    // Известная манера китайских моделей — уронить иероглиф вместо слова.
    // Предложение с дырой хуже целого, но лучше иероглифов на витрине,
    // и несравнимо лучше потерянного ответа целиком.
    $formatter = new ReplyFormatter;

    expect($formatter->format('Если эта цена超出了 ваш бюджет, подскажите.'))
        ->toBe('Если эта цена ваш бюджет, подскажите.')
        ->and($formatter->format('Компрессор 100 л, 2,2 кВт — 69 459 ₽.'))
        ->toBe('Компрессор 100 л, 2,2 кВт — 69 459 ₽.');
});

it('не принимает за иероглифы кириллицу, латиницу и знаки', function (): void {
    $formatter = new ReplyFormatter;
    $text = 'Ø100 мм, хвостовик Weldon 31,75 мм — «EUROBOOR», 69 459 ₽ (в наличии).';

    expect($formatter->format($text))->toBe($text);
});

it('разворачивает markdown-таблицу в список', function (): void {
    // Панель шириной 380 пикселей, расширение таблиц у парсера не
    // подключено с 3.10, и промпт таблицы запрещает — но 04.09.2026
    // модель выдала их дважды подряд, и покупатель увидел сырые палки.
    $formatter = new ReplyFormatter;

    $text = "Вот модели:\n\n"
        ."| Модель | Цена | Ход штока |\n"
        ."|--------|------|-----------|\n"
        ."| ДГ500-100Г | 277 326 ₽ | 100 мм |\n"
        ."| ДГ500-150Г | 306 714 ₽ | 150 мм |\n\n"
        .'Гарантия 12 месяцев.';

    expect($formatter->format($text))->toBe(
        "Вот модели:\n\n"
        ."- **ДГ500-100Г** — 277 326 ₽ · 100 мм\n"
        ."- **ДГ500-150Г** — 306 714 ₽ · 150 мм\n\n"
        .'Гарантия 12 месяцев.'
    );
});

it('не трогает обычный текст с вертикальной чертой', function (): void {
    $formatter = new ReplyFormatter;
    $text = 'Напряжение 220|380 В — уточните, какое у вас.';

    expect($formatter->format($text))->toBe($text);
});

it('выбрасывает сумму, которой этот посетитель на витрине не видит', function (): void {
    /*
     * Последний слой защиты цены для зарегистрированных. Первый — устройство
     * ProductCard, где второго поля с ценой нет; второй — запрет арифметики
     * в промпте. Этот нужен потому, что к сумме можно прийти и мимо данных:
     * посчитать из процента, вспомнить из хода, когда покупатель был
     * в аккаунте, или просто угадать.
     */
    $formatter = new ReplyFormatter;

    expect($formatter->format('Цена 108 596 руб. Со скидкой выйдет 103 166 руб. Есть в наличии.', [103166]))
        ->toBe('Цена 108 596 руб. Есть в наличии.')
        // Слитная запись и неразрывный пробел — то же число.
        ->and($formatter->format('Для вас будет 103166 руб.', [103166]))->toBe('')
        ->and($formatter->format("Со скидкой 103\u{00A0}166 руб. Оформить?", [103166]))->toBe('Оформить?');
});

it('не трогает цены, которые магазин показывает открыто', function (): void {
    $formatter = new ReplyFormatter;
    $text = 'Компрессор стоит 108 596 руб., на него действует скидка 5% для зарегистрированных.';

    expect($formatter->format($text, [103166]))->toBe($text)
        // Проценты и штуки суммами не считаются — иначе «скидка 5%»
        // выбрасывалась бы вместе с половиной ответа.
        ->and($formatter->format('Скидка 5% при заказе 3 позиций.', [5, 3]))
        ->toBe('Скидка 5% при заказе 3 позиций.')
        ->and($formatter->format($text, []))->toBe($text);
});

it('переживает таблицу без шапки и с пустыми ячейками', function (): void {
    $formatter = new ReplyFormatter;
    $text = "| Модель | Цена |\n|---|---|\n| ДГ500 |  |";

    expect($formatter->format($text))->toBe('- **ДГ500**');
});
